use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use syn::punctuated::Punctuated;
use syn::{Expr, Fields, GenericArgument, Item, Lit, PathArguments, ReturnType, Stmt, Token, Type, UnOp};

use crate::remote_mappers::{camel_case, screaming_snake_case, swift_case, uniffi_swift_case, uniffi_type_name};

pub const HEADER: &str = "// Generated by `just generate-models`. Do not edit.\n// Declared in core/gemstone/src/constants.rs.\n";
pub const SOURCE: &str = "gemstone/src/constants.rs";
pub const TYPE_ROOTS: [&str; 2] = ["gemstone/src", "crates/primitives/src"];
pub const SWIFT_PATH: &str = "GemstonePrimitives/Sources/Generated/GemConstants.swift";
pub const KOTLIN_PATH: &str = "../../gemwallet/android/ext/GemConstants.kt";
const PRIMITIVES_ROOT: &str = "crates/primitives/src";

/// `constants.rs`: fixed values Core reads and both apps receive as generated constants instead of FFI calls.
pub struct Constants {
    items: Vec<Constant>,
    values: BTreeMap<String, Expr>,
    types: BTreeMap<String, Declaration>,
}

struct Constant {
    name: String,
    ty: Type,
    value: Expr,
}

struct Declaration {
    item: Item,
    typeshared: bool,
    kotlin_package: String,
}

#[derive(Clone, Copy, PartialEq)]
enum Language {
    Swift,
    Kotlin,
}

#[derive(Clone, Copy, PartialEq)]
enum Space {
    Core,
    App,
}

impl Constants {
    pub fn load(root: &Path) -> Self {
        let roots: Vec<PathBuf> = TYPE_ROOTS.iter().map(|path| root.join(path)).collect();
        Self::parse(&fs::read_to_string(root.join(SOURCE)).expect("constants.rs is missing"), &roots, &root.join(PRIMITIVES_ROOT))
    }

    pub fn parse(source: &str, type_roots: &[PathBuf], primitives: &Path) -> Self {
        let file = syn::parse_file(source).expect("constants.rs does not parse");
        let items = file.items.iter().filter_map(constant).collect();
        let values = file
            .items
            .iter()
            .filter_map(|item| match item {
                Item::Const(constant) => Some((constant.ident.to_string(), (*constant.expr).clone())),
                _ => None,
            })
            .collect();
        let mut types = BTreeMap::new();
        for root in type_roots {
            for path in rust_files(root) {
                let Ok(parsed) = syn::parse_file(&fs::read_to_string(&path).unwrap_or_default()) else {
                    continue;
                };
                for item in parsed.items {
                    if let Some(name) = declared_name(&item) {
                        let typeshared = has_attribute(&item, "typeshare");
                        let kotlin_package = kotlin_package(&path, primitives);
                        if !typeshared && types.contains_key(&name) {
                            continue;
                        }
                        types.insert(name, Declaration { item, typeshared, kotlin_package });
                    }
                }
            }
        }
        Self { items, values, types }
    }

    pub fn swift(&self) -> String {
        let members: Vec<String> = self
            .items
            .iter()
            .map(|constant| {
                let space = self.space(&constant.ty);
                format!(
                    "    public static let {}: {} = {}\n",
                    constant.name,
                    self.type_name(&constant.ty, Language::Swift, space),
                    self.literal(&constant.ty, &constant.value, Language::Swift, space)
                )
            })
            .collect();
        format!("{HEADER}\nimport Foundation\nimport Gemstone\nimport Primitives\n\npublic enum GemConstants {{\n{}}}\n", members.join(""))
    }

    pub fn kotlin(&self) -> String {
        let members: Vec<String> = self
            .items
            .iter()
            .map(|constant| {
                let space = self.space(&constant.ty);
                format!(
                    "    val {}: {} = {}\n",
                    constant.name,
                    self.type_name(&constant.ty, Language::Kotlin, space),
                    self.literal(&constant.ty, &constant.value, Language::Kotlin, space)
                )
            })
            .collect();
        let body = members.join("");
        let imports: Vec<&str> = [
            ("kotlin.time.Duration", ": Duration"),
            ("kotlin.time.Duration.Companion.milliseconds", ".milliseconds"),
            ("kotlin.time.Duration.Companion.seconds", ".seconds"),
        ]
        .into_iter()
        .filter(|(_, usage)| body.contains(usage))
        .map(|(import, _)| import)
        .collect();
        let imports: String = imports.iter().map(|import| format!("import {import}\n")).collect();
        format!("{HEADER}\npackage com.gemwallet.android.ext\n\n{imports}\nobject GemConstants {{\n{body}}}\n")
    }

    /// A constant whose type is a TypeShare type reaches the app as the app's own type; everything else keeps the binding type.
    fn space(&self, ty: &Type) -> Space {
        match self.named(element(ty)) {
            Some(declaration) if declaration.typeshared => Space::App,
            _ => Space::Core,
        }
    }

    fn named(&self, ty: &Type) -> Option<&Declaration> {
        self.types.get(&type_ident(ty)?)
    }

    fn type_name(&self, ty: &Type, language: Language, space: Space) -> String {
        if let Some(inner) = list_element(ty) {
            let inner = self.type_name(inner, language, space);
            return match language {
                Language::Swift => format!("[{inner}]"),
                Language::Kotlin => format!("List<{inner}>"),
            };
        }
        if let Some(inner) = generic_argument(ty, "Option") {
            return format!("{}?", self.type_name(inner, language, space));
        }
        if is_str(ty) {
            return "String".to_string();
        }
        let name = type_ident(ty).unwrap_or_else(|| panic!("constants.rs uses a type the generator cannot name: {}", quote(ty)));
        match (scalar(&name, language), language) {
            (Some(scalar), _) => scalar.to_string(),
            (None, language) => self.qualified(&name, language, space),
        }
    }

    fn qualified(&self, name: &str, language: Language, space: Space) -> String {
        let declaration = self.types.get(name).unwrap_or_else(|| panic!("constants.rs uses {name}, which is declared in neither gemstone nor primitives"));
        match (language, space, declaration.typeshared) {
            (Language::Swift, Space::App, true) => format!("Primitives.{name}"),
            (Language::Swift, _, _) => format!("Gemstone.{name}"),
            (Language::Kotlin, Space::App, true) => format!("{}.{name}", declaration.kotlin_package),
            (Language::Kotlin, _, _) => format!("uniffi.gemstone.{name}"),
        }
    }

    fn literal(&self, ty: &Type, value: &Expr, language: Language, space: Space) -> String {
        let value = self.resolve(value);
        if let Some(inner) = list_element(ty) {
            let elements: Vec<String> = list_elements(value).iter().map(|element| self.literal(inner, element, language, space)).collect();
            return match language {
                Language::Swift => format!("[{}]", elements.join(", ")),
                Language::Kotlin => format!("listOf<{}>({})", self.type_name(inner, language, space), elements.join(", ")),
            };
        }
        if let Some(inner) = generic_argument(ty, "Option") {
            return match option_value(value) {
                None if language == Language::Swift => "nil".to_string(),
                None => "null".to_string(),
                Some(inner_value) => self.literal(inner, inner_value, language, space),
            };
        }
        if is_str(ty) {
            return string_literal(value, language);
        }
        let name = type_ident(ty).unwrap_or_default();
        match name.as_str() {
            "String" => string_literal(value, language),
            "bool" => match value {
                Expr::Lit(literal) => match &literal.lit {
                    Lit::Bool(flag) => flag.value.to_string(),
                    _ => panic!("expected a bool, found {}", quote(value)),
                },
                _ => panic!("expected a bool, found {}", quote(value)),
            },
            "f32" | "f64" => float_literal(value),
            "Duration" => duration_literal(value, language),
            name if scalar(name, language).is_some() => integer_literal(name, value, language),
            name => self.named_literal(name, value, language, space),
        }
    }

    fn named_literal(&self, name: &str, value: &Expr, language: Language, space: Space) -> String {
        let declaration = self.types.get(name).unwrap_or_else(|| panic!("constants.rs uses {name}, which is declared in neither gemstone nor primitives"));
        let qualified = self.qualified(name, language, space);
        let app = space == Space::App && declaration.typeshared;
        match &declaration.item {
            Item::Struct(record) => {
                let Expr::Struct(literal) = value else {
                    panic!("{name} needs a struct literal, found {}", quote(value));
                };
                let Fields::Named(fields) = &record.fields else {
                    panic!("{name} is not a record with named fields");
                };
                let arguments: Vec<String> = fields
                    .named
                    .iter()
                    .map(|field| {
                        let ident = field.ident.as_ref().map(ToString::to_string).unwrap_or_default();
                        let value = literal
                            .fields
                            .iter()
                            .find(|initializer| member_name(&initializer.member) == ident)
                            .map(|initializer| &initializer.expr)
                            .unwrap_or_else(|| panic!("{name} literal is missing {ident}"));
                        let rendered = self.literal(&field.ty, value, language, space);
                        match language {
                            Language::Swift => format!("{}: {rendered}", camel_case(&ident)),
                            Language::Kotlin => format!("{} = {rendered}", camel_case(&ident)),
                        }
                    })
                    .collect();
                format!("{qualified}({})", arguments.join(", "))
            }
            Item::Enum(enumeration) => {
                let (variant_name, fields) = variant_value(value);
                let variant = enumeration.variants.iter().find(|variant| variant.ident == variant_name).unwrap_or_else(|| panic!("{name} has no variant {variant_name}"));
                let flat = enumeration.variants.iter().all(|variant| matches!(variant.fields, Fields::Unit));
                let case = match (language, app, flat) {
                    (Language::Swift, true, _) => swift_case(&variant_name),
                    (Language::Swift, false, _) => uniffi_swift_case(&variant_name),
                    (Language::Kotlin, true, _) => variant_name.clone(),
                    (Language::Kotlin, false, true) => screaming_snake_case(&variant_name),
                    (Language::Kotlin, false, false) => uniffi_type_name(&variant_name),
                };
                let arguments: Vec<String> = match &variant.fields {
                    Fields::Unit => return format!("{qualified}.{case}"),
                    Fields::Named(named) => named
                        .named
                        .iter()
                        .map(|field| {
                            let ident = field.ident.as_ref().map(ToString::to_string).unwrap_or_default();
                            let value = fields.iter().find(|(label, _)| *label == ident).map(|(_, value)| *value).unwrap_or_else(|| panic!("{name}::{variant_name} is missing {ident}"));
                            let rendered = self.literal(&field.ty, value, language, space);
                            match language {
                                Language::Swift => format!("{}: {rendered}", camel_case(&ident)),
                                Language::Kotlin => format!("{} = {rendered}", camel_case(&ident)),
                            }
                        })
                        .collect(),
                    Fields::Unnamed(unnamed) => unnamed.unnamed.iter().zip(fields.iter()).map(|(field, (_, value))| self.literal(&field.ty, value, language, space)).collect(),
                };
                format!("{qualified}.{case}({})", arguments.join(", "))
            }
            _ => panic!("{name} is neither a record nor an enum"),
        }
    }

    /// A path to another constant of `constants.rs`, public or not, stands for that constant's value.
    fn resolve<'a>(&'a self, value: &'a Expr) -> &'a Expr {
        let Expr::Path(path) = value else {
            return value;
        };
        let Some(ident) = path.path.get_ident() else {
            return value;
        };
        self.values.get(&ident.to_string()).map(|value| self.resolve(value)).unwrap_or(value)
    }
}

fn constant(item: &Item) -> Option<Constant> {
    match item {
        Item::Const(constant) if is_public(&constant.vis) => Some(Constant {
            name: constant_name(&constant.ident.to_string()),
            ty: (*constant.ty).clone(),
            value: (*constant.expr).clone(),
        }),
        Item::Fn(function) if is_public(&function.vis) && function.sig.inputs.is_empty() => {
            let ReturnType::Type(_, ty) = &function.sig.output else {
                panic!("{} returns nothing", function.sig.ident);
            };
            let [Stmt::Expr(value, None)] = function.block.stmts.as_slice() else {
                panic!("{} must be a single expression", function.sig.ident);
            };
            Some(Constant {
                name: camel_case(&function.sig.ident.to_string()),
                ty: (**ty).clone(),
                value: value.clone(),
            })
        }
        _ => None,
    }
}

fn constant_name(name: &str) -> String {
    camel_case(&name.to_ascii_lowercase())
}

fn is_public(visibility: &syn::Visibility) -> bool {
    matches!(visibility, syn::Visibility::Public(_))
}

fn declared_name(item: &Item) -> Option<String> {
    match item {
        Item::Struct(record) => Some(record.ident.to_string()),
        Item::Enum(enumeration) => Some(enumeration.ident.to_string()),
        _ => None,
    }
}

fn has_attribute(item: &Item, name: &str) -> bool {
    let attributes = match item {
        Item::Struct(record) => &record.attrs,
        Item::Enum(enumeration) => &enumeration.attrs,
        _ => return false,
    };
    attributes.iter().any(|attribute| attribute.path().is_ident(name))
}

fn kotlin_package(path: &Path, primitives: &Path) -> String {
    let Ok(relative) = path.strip_prefix(primitives) else {
        return "uniffi.gemstone".to_string();
    };
    let directories: Vec<String> = relative.parent().into_iter().flat_map(|parent| parent.iter()).map(|part| part.to_string_lossy().to_lowercase()).collect();
    ["com.wallet.core.primitives".to_string()].into_iter().chain(directories).collect::<Vec<_>>().join(".")
}

fn rust_files(root: &Path) -> Vec<PathBuf> {
    let Ok(entries) = fs::read_dir(root) else {
        return Vec::new();
    };
    let mut paths: Vec<PathBuf> = entries.filter_map(Result::ok).map(|entry| entry.path()).collect();
    paths.sort();
    paths
        .into_iter()
        .flat_map(|path| match path.is_dir() {
            true => rust_files(&path),
            false if path.extension().is_some_and(|extension| extension == "rs") => vec![path],
            false => Vec::new(),
        })
        .collect()
}

fn scalar(name: &str, language: Language) -> Option<&'static str> {
    let names = match name {
        "u8" => ("UInt8", "UByte"),
        "u16" => ("UInt16", "UShort"),
        "u32" => ("UInt32", "UInt"),
        "u64" => ("UInt64", "ULong"),
        "i8" => ("Int8", "Byte"),
        "i16" => ("Int16", "Short"),
        "i32" => ("Int32", "Int"),
        "i64" => ("Int64", "Long"),
        "usize" => ("Int", "Int"),
        "f32" => ("Float", "Float"),
        "f64" => ("Double", "Double"),
        "bool" => ("Bool", "Boolean"),
        "String" => ("String", "String"),
        "Duration" => ("Duration", "Duration"),
        _ => return None,
    };
    Some(match language {
        Language::Swift => names.0,
        Language::Kotlin => names.1,
    })
}

fn integer_literal(name: &str, value: &Expr, language: Language) -> String {
    let digits = match value {
        Expr::Lit(literal) => match &literal.lit {
            Lit::Int(integer) => integer.base10_digits().to_string(),
            _ => panic!("expected an integer, found {}", quote(value)),
        },
        Expr::Unary(unary) if matches!(unary.op, UnOp::Neg(_)) => format!("-{}", integer_literal(name, &unary.expr, Language::Swift)),
        _ => panic!("expected an integer, found {}", quote(value)),
    };
    let suffix = match (language, name) {
        (Language::Swift, _) => "",
        (Language::Kotlin, "u8" | "u16" | "u32") => "u",
        (Language::Kotlin, "u64") => "uL",
        (Language::Kotlin, "i64") => "L",
        (Language::Kotlin, _) => "",
    };
    format!("{digits}{suffix}")
}

fn float_literal(value: &Expr) -> String {
    match value {
        Expr::Lit(literal) => match &literal.lit {
            Lit::Float(float) => float.base10_digits().to_string(),
            Lit::Int(integer) => format!("{}.0", integer.base10_digits()),
            _ => panic!("expected a number, found {}", quote(value)),
        },
        Expr::Unary(unary) if matches!(unary.op, UnOp::Neg(_)) => format!("-{}", float_literal(&unary.expr)),
        _ => panic!("expected a number, found {}", quote(value)),
    }
}

fn duration_literal(value: &Expr, language: Language) -> String {
    let Expr::Call(call) = value else {
        panic!("a Duration is written Duration::from_millis(..) or Duration::from_secs(..), found {}", quote(value));
    };
    let Expr::Path(function) = &*call.func else {
        panic!("expected a Duration constructor, found {}", quote(value));
    };
    let unit = match function.path.segments.last().map(|segment| segment.ident.to_string()).as_deref() {
        Some("from_millis") => "milliseconds",
        Some("from_secs") => "seconds",
        other => panic!("unsupported Duration constructor {other:?}"),
    };
    let amount = call.args.first().map(|argument| integer_literal("u64", argument, Language::Swift)).unwrap_or_default();
    match language {
        Language::Swift => format!(".{unit}({amount})"),
        Language::Kotlin => format!("{amount}.{unit}"),
    }
}

fn string_literal(value: &Expr, language: Language) -> String {
    let text = match value {
        Expr::Lit(literal) => match &literal.lit {
            Lit::Str(text) => text.value(),
            _ => panic!("expected a string, found {}", quote(value)),
        },
        Expr::MethodCall(call) if ["to_string", "to_owned", "into"].contains(&call.method.to_string().as_str()) => return string_literal(&call.receiver, language),
        Expr::Call(call) if call.args.len() == 1 => return string_literal(&call.args[0], language),
        _ => panic!("expected a string, found {}", quote(value)),
    };
    let escaped: String = text
        .chars()
        .flat_map(|character| match character {
            '"' => vec!['\\', '"'],
            '\\' => vec!['\\', '\\'],
            '$' if language == Language::Kotlin => vec!['\\', '$'],
            '\n' => vec!['\\', 'n'],
            character => vec![character],
        })
        .collect();
    format!("\"{escaped}\"")
}

fn list_elements(value: &Expr) -> Vec<Expr> {
    match value {
        Expr::Reference(reference) => list_elements(&reference.expr),
        Expr::Array(array) => array.elems.iter().cloned().collect(),
        Expr::Macro(invocation) if invocation.mac.path.is_ident("vec") => invocation.mac.parse_body_with(Punctuated::<Expr, Token![,]>::parse_terminated).expect("vec! holds a list of expressions").into_iter().collect(),
        _ => panic!("expected a list, found {}", quote(value)),
    }
}

fn option_value(value: &Expr) -> Option<&Expr> {
    match value {
        Expr::Path(path) if path.path.is_ident("None") => None,
        Expr::Call(call) if matches!(&*call.func, Expr::Path(path) if path.path.is_ident("Some")) => call.args.first(),
        _ => panic!("expected None or Some(..), found {}", quote(value)),
    }
}

fn variant_value(value: &Expr) -> (String, Vec<(String, &Expr)>) {
    match value {
        Expr::Path(path) => (last_segment(&path.path), Vec::new()),
        Expr::Struct(literal) => (last_segment(&literal.path), literal.fields.iter().map(|field| (member_name(&field.member), &field.expr)).collect()),
        Expr::Call(call) => {
            let Expr::Path(path) = &*call.func else {
                panic!("expected an enum variant, found {}", quote(value));
            };
            (last_segment(&path.path), call.args.iter().enumerate().map(|(index, argument)| (index.to_string(), argument)).collect())
        }
        _ => panic!("expected an enum variant, found {}", quote(value)),
    }
}

fn member_name(member: &syn::Member) -> String {
    match member {
        syn::Member::Named(ident) => ident.to_string(),
        syn::Member::Unnamed(index) => index.index.to_string(),
    }
}

fn last_segment(path: &syn::Path) -> String {
    path.segments.last().map(|segment| segment.ident.to_string()).unwrap_or_default()
}

fn type_ident(ty: &Type) -> Option<String> {
    match ty {
        Type::Path(path) => path.path.segments.last().map(|segment| segment.ident.to_string()),
        _ => None,
    }
}

fn is_str(ty: &Type) -> bool {
    matches!(ty, Type::Reference(reference) if matches!(&*reference.elem, Type::Path(path) if path.path.is_ident("str")))
}

fn list_element(ty: &Type) -> Option<&Type> {
    match ty {
        Type::Reference(reference) => match &*reference.elem {
            Type::Slice(slice) => Some(&slice.elem),
            _ => None,
        },
        _ => generic_argument(ty, "Vec"),
    }
}

fn generic_argument<'a>(ty: &'a Type, wrapper: &str) -> Option<&'a Type> {
    let Type::Path(path) = ty else {
        return None;
    };
    let segment = path.path.segments.last()?;
    if segment.ident != wrapper {
        return None;
    }
    let PathArguments::AngleBracketed(arguments) = &segment.arguments else {
        return None;
    };
    arguments.args.iter().find_map(|argument| match argument {
        GenericArgument::Type(inner) => Some(inner),
        _ => None,
    })
}

fn element(ty: &Type) -> &Type {
    list_element(ty).or_else(|| generic_argument(ty, "Option")).map(element).unwrap_or(ty)
}

fn quote(tokens: &impl quote::ToTokens) -> String {
    tokens.to_token_stream().to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn testdata() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("testdata").join("constants")
    }

    fn generator() -> Constants {
        let root = testdata();
        Constants::parse(&fs::read_to_string(root.join("constants.rs")).unwrap(), &[root.join("types"), root.join("primitives")], &root.join("primitives"))
    }

    fn expect_generated(name: &str, actual: String) {
        let path = testdata().join("expected").join(name);
        if std::env::var("UPDATE_GOLDEN").is_ok() {
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(&path, &actual).unwrap();
        }
        let expected = fs::read_to_string(&path).unwrap_or_else(|_| panic!("{} is missing; run the tests once with UPDATE_GOLDEN=1", path.display()));
        assert_eq!(actual, expected, "{name} no longer matches testdata/constants/expected/{name}; rerun with UPDATE_GOLDEN=1 once the diff is intended");
    }

    #[test]
    fn test_swift_constants_match_the_expected_file() {
        expect_generated("GemConstants.swift", generator().swift());
    }

    #[test]
    fn test_kotlin_constants_match_the_expected_file() {
        expect_generated("GemConstants.kt", generator().kotlin());
    }

    #[test]
    fn test_the_checked_in_app_constants_are_current() {
        let core = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let constants = Constants::load(&core);
        let swift = fs::read_to_string(core.join("../ios/Packages").join(SWIFT_PATH)).expect("GemConstants.swift is missing; run just generate-models");
        let kotlin = fs::read_to_string(core.join("../android/gemcore/src/main/kotlin/com/wallet/core").join(KOTLIN_PATH)).expect("GemConstants.kt is missing; run just generate-models");
        assert_eq!(swift, constants.swift(), "GemConstants.swift is stale; run just generate-models");
        assert_eq!(kotlin, constants.kotlin(), "GemConstants.kt is stale; run just generate-models");
    }
}
