use crate::remote_mappers::{Generator, RemoteType, uniffi_type_name};

const HEADER: &str = "// Generated by `just generate-models`. Do not edit.\n// Every UniFFI record core/gemstone/src declares with an `id` field.\n";

impl Generator {
    pub fn swift_identifiable(&self) -> String {
        let conformances = self
            .core_records
            .iter()
            .filter(|name| matches!(self.core_types.get(*name), Some(RemoteType::Record { fields, .. }) if fields.iter().any(|field| field.rust == "id")))
            .map(|name| format!("extension {}: Identifiable {{}}\n", uniffi_type_name(name)))
            .collect::<String>();
        format!("{HEADER}\n{conformances}")
    }
}

#[cfg(test)]
mod tests {
    use crate::remote_mappers::Generator;
    use crate::testkit::expect_generated;

    #[test]
    fn test_swift_identifiable_matches_the_expected_file() {
        expect_generated("IdentifiableRecords.swift", Generator::mock().swift_identifiable());
    }
}
