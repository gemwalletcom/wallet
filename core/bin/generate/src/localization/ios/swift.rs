enum Placeholder {
    Object,
    Integer,
}

#[derive(Default)]
struct Node {
    values: BTreeMap<String, (String, String)>,
    children: BTreeMap<String, Node>,
}

pub fn source(enum_name: &str, entries: &BTreeMap<String, String>) -> Result<String, Box<dyn Error + Send + Sync>> {
    let root = build_tree(entries)?;
    let mut output = format!(
        "// swiftlint:disable all\n// Generated by `just localize` — do not edit.\n\nimport Foundation\n\n// swiftlint:disable superfluous_disable_command file_length implicit_return prefer_self_in_static_references\n\n// MARK: - Strings\n\n// swiftlint:disable explicit_type_interface function_parameter_count identifier_name line_length\n// swiftlint:disable nesting type_body_length type_name vertical_whitespace_opening_braces\npublic enum {enum_name} {{\n"
    );
    write_node(&mut output, &root, enum_name, 1);
    output.push_str(&format!(
        "}}\n// swiftlint:enable explicit_type_interface function_parameter_count identifier_name line_length\n// swiftlint:enable nesting type_body_length type_name vertical_whitespace_opening_braces\n\n// MARK: - Implementation Details\n\nextension {enum_name} {{\n  private static func tr(_ table: String, _ key: String, _ args: CVarArg..., fallback value: String) -> String {{\n    let format = BundleToken.bundle.localizedString(forKey: key, value: value, table: table)\n    return String(format: format, locale: Locale.current, arguments: args)\n  }}\n}}\n\n// swiftlint:disable convenience_type\nprivate final class BundleToken {{\n  static let bundle: Bundle = {{\n    #if SWIFT_PACKAGE\n    return Bundle.module\n    #else\n    return Bundle(for: BundleToken.self)\n    #endif\n  }}()\n}}\n// swiftlint:enable convenience_type\n"
    ));
    Ok(output)
}

fn build_tree(entries: &BTreeMap<String, String>) -> Result<Node, Box<dyn Error + Send + Sync>> {
    let mut root = Node::default();
    for (key, value) in entries {
        let segments = key.split('.').collect::<Vec<_>>();
        let (leaf, path) = segments.split_last().ok_or_else(|| format!("empty key {key}"))?;
        let mut node = &mut root;
        for segment in path {
            node = node.children.entry(segment.to_string()).or_default();
        }
        if node.values.insert(leaf.to_string(), (key.clone(), value.clone())).is_some() {
            return Err(format!("key {key} maps to a duplicate name at {leaf}").into());
        }
    }
    Ok(root)
}

fn write_node(output: &mut String, node: &Node, enum_name: &str, level: usize) {
    let indent = "  ".repeat(level);
    for (segment, (key, value)) in &node.values {
        for line in value.split(ESCAPED_NEWLINE) {
            output.push_str(&format!("{indent}/// {line}\n"));
        }
        let name = property_name(segment);
        let placeholders = placeholders(value);
        if placeholders.is_empty() {
            output.push_str(&format!(
                "{indent}public static let {name} = {enum_name}.tr(\"{TABLE_NAME}\", \"{key}\", fallback: \"{value}\")\n"
            ));
        } else {
            let parameters = placeholders
                .iter()
                .enumerate()
                .map(|(index, placeholder)| match placeholder {
                    Placeholder::Object => format!("_ p{}: Any", index + 1),
                    Placeholder::Integer => format!("_ p{}: Int", index + 1),
                })
                .collect::<Vec<_>>()
                .join(", ");
            let arguments = placeholders
                .iter()
                .enumerate()
                .map(|(index, placeholder)| match placeholder {
                    Placeholder::Object => format!("String(describing: p{})", index + 1),
                    Placeholder::Integer => format!("p{}", index + 1),
                })
                .collect::<Vec<_>>()
                .join(", ");
            output.push_str(&format!("{indent}public static func {name}({parameters}) -> String {{\n"));
            output.push_str(&format!(
                "{indent}  return {enum_name}.tr(\"{TABLE_NAME}\", \"{key}\", {arguments}, fallback: \"{value}\")\n"
            ));
            output.push_str(&format!("{indent}}}\n"));
        }
    }
    for (segment, child) in &node.children {
        output.push_str(&format!("{indent}public enum {} {{\n", type_name(segment)));
        write_node(output, child, enum_name, level + 1);
        output.push_str(&format!("{indent}}}\n"));
    }
}

fn placeholders(value: &str) -> Vec<Placeholder> {
    let mut placeholders = Vec::new();
    let mut characters = value.chars().peekable();
    while let Some(character) = characters.next() {
        if character == '%' {
            match characters.peek() {
                Some('@') => {
                    characters.next();
                    placeholders.push(Placeholder::Object);
                }
                Some('d') => {
                    characters.next();
                    placeholders.push(Placeholder::Integer);
                }
                _ => {}
            }
        }
    }
    placeholders
}

fn property_name(segment: &str) -> String {
    let name = camel_case(segment);
    let mut characters = name.chars();
    let name = match characters.next() {
        Some(first) => first.to_lowercase().collect::<String>() + characters.as_str(),
        None => name,
    };
    if RESERVED_WORDS.contains(&name.as_str()) {
        return format!("`{name}`");
    }
    name
}

fn type_name(segment: &str) -> String {
    camel_case(segment)
}

fn camel_case(segment: &str) -> String {
    segment
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut characters = part.chars();
            match characters.next() {
                Some(first) => first.to_uppercase().collect::<String>() + characters.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_source() {
        let entries = BTreeMap::from([
            ("common.continue".to_string(), "Continue".to_string()),
            ("common.maximum_value".to_string(), "Maximum value is %@".to_string()),
            ("transfer.state.latency".to_string(), "%d ms".to_string()),
            ("welcome.title".to_string(), "First line\\nSecond line".to_string()),
        ]);
        let source = source("Localized", &entries).unwrap();
        assert!(source.contains("public enum Localized {"));
        assert!(source.contains("    public static let `continue` = Localized.tr(\"Localizable\", \"common.continue\", fallback: \"Continue\")"));
        assert!(source.contains("    public static func maximumValue(_ p1: Any) -> String {"));
        assert!(source.contains("      return Localized.tr(\"Localizable\", \"common.maximum_value\", String(describing: p1), fallback: \"Maximum value is %@\")"));
        assert!(source.contains("      public static func latency(_ p1: Int) -> String {"));
        assert!(source.contains("        return Localized.tr(\"Localizable\", \"transfer.state.latency\", p1, fallback: \"%d ms\")"));
        assert!(source.contains(
            "    /// First line\n    /// Second line\n    public static let title = Localized.tr(\"Localizable\", \"welcome.title\", fallback: \"First line\\nSecond line\")"
        ));
        assert!(source.contains("  public enum Transfer {\n    public enum State {"));
        let coexisting = super::source("Localized", &BTreeMap::from([("a.b".to_string(), "x".to_string()), ("a.b.c".to_string(), "y".to_string())])).unwrap();
        assert!(coexisting.contains("    public static let b = Localized.tr(\"Localizable\", \"a.b\", fallback: \"x\")"));
        assert!(coexisting.contains("    public enum B {"));
    }
}
