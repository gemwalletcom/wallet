#[derive(Deserialize)]
pub struct TypeMappings {
    swift: BTreeMap<String, String>,
    kotlin: BTreeMap<String, String>,
}

#[derive(Deserialize)]
struct MappingsConfig {
    type_mappings: TypeMappings,
}

impl TypeMappings {
    pub fn from_yaml(yaml: &str) -> Self {
        config::Config::builder()
            .add_source(File::from_str(yaml, FileFormat::Yaml))
            .build()
            .and_then(|config| config.try_deserialize::<MappingsConfig>())
            .expect("invalid type_mappings")
            .type_mappings
    }
}

#[derive(Clone, Debug)]
enum Type {
    Named(String, Vec<Type>),
    List(Box<Type>),
    Optional(Box<Type>),
    Map(Box<Type>, Box<Type>),
    String,
    Char,
    Bool,
    I8,
    I16,
    I32,
    U8,
    U16,
    U32,
    F32,
    F64,
}

impl Type {
    fn parse(ty: &syn::Type) -> Result<Self, String> {
        match ty {
            syn::Type::Reference(reference) => Self::parse(&reference.elem),
            syn::Type::Array(array) => Ok(Self::List(Box::new(Self::parse(&array.elem)?))),
            syn::Type::Slice(slice) => Ok(Self::List(Box::new(Self::parse(&slice.elem)?))),
            syn::Type::Path(path) => {
                let segment = path.path.segments.last().ok_or("empty type path")?;
                let parameters = match &segment.arguments {
                    PathArguments::AngleBracketed(arguments) => arguments
                        .args
                        .iter()
                        .filter_map(|argument| match argument {
                            GenericArgument::Type(ty) => Some(Self::parse(ty)),
                            _ => None,
                        })
                        .collect::<Result<Vec<_>, _>>()?,
                    _ => vec![],
                };
                let first = || parameters.first().cloned().ok_or_else(|| format!("{} needs a type parameter", segment.ident));
                Ok(match segment.ident.to_string().as_str() {
                    "Vec" => Self::List(Box::new(first()?)),
                    "Option" => Self::Optional(Box::new(first()?)),
                    "HashMap" => match parameters.as_slice() {
                        [key, value] => Self::Map(Box::new(key.clone()), Box::new(value.clone())),
                        _ => return Err("HashMap needs a key and a value type".into()),
                    },
                    "str" | "String" => Self::String,
                    "Box" | "Weak" | "Arc" | "Rc" | "Cow" | "ArcWeak" | "RcWeak" | "Cell" | "Mutex" | "RefCell" | "RwLock" => first()?,
                    "bool" => Self::Bool,
                    "char" => Self::Char,
                    "u8" => Self::U8,
                    "u16" => Self::U16,
                    "u32" => Self::U32,
                    "i8" => Self::I8,
                    "i16" => Self::I16,
                    "i32" => Self::I32,
                    "f32" => Self::F32,
                    "f64" => Self::F64,
                    unsupported @ ("i64" | "usize" | "isize") => return Err(format!("{unsupported} is not supported")),
                    name => Self::Named(name.to_string(), parameters),
                })
            }
            other => Err(format!("unsupported type: {}", quote::ToTokens::to_token_stream(other))),
        }
    }

    fn contains(&self, name: &str) -> bool {
        match self {
            Self::Named(id, parameters) => id == name || parameters.iter().any(|parameter| parameter.contains(name)),
            Self::List(inner) | Self::Optional(inner) => inner.contains(name),
            Self::Map(key, value) => key.contains(name) || value.contains(name),
            _ => false,
        }
    }

    fn optional_value(&self) -> Option<&Type> {
        match self {
            Self::Optional(inner) => Some(inner),
            _ => None,
        }
    }

    fn is_optional(&self) -> bool {
        self.optional_value().is_some()
    }

    fn swift(&self, mappings: &BTreeMap<String, String>) -> String {
        match self {
            Self::Named(name, parameters) => match (mappings.get(name), parameters.is_empty()) {
                (Some(mapped), _) => mapped.clone(),
                (None, true) => name.clone(),
                (None, false) => format!("{name}<{}>", parameters.iter().map(|parameter| parameter.swift(mappings)).collect::<Vec<_>>().join(", ")),
            },
            Self::List(inner) => format!("[{}]", inner.swift(mappings)),
            Self::Optional(inner) => format!("{}?", inner.swift(mappings)),
            Self::Map(key, value) => format!("[{}: {}]", key.swift(mappings), value.swift(mappings)),
            Self::String => "String".into(),
            Self::Char => "Unicode.Scalar".into(),
            Self::Bool => "Bool".into(),
            Self::I8 => "Int8".into(),
            Self::I16 => "Int16".into(),
            Self::I32 => "Int32".into(),
            Self::U8 => "UInt8".into(),
            Self::U16 => "UInt16".into(),
            Self::U32 => "UInt32".into(),
            Self::F32 => "Float".into(),
            Self::F64 => "Double".into(),
        }
    }

    fn kotlin(&self, mappings: &BTreeMap<String, String>) -> String {
        match self {
            Self::Named(name, parameters) => match (mappings.get(name), parameters.is_empty()) {
                (Some(mapped), _) => mapped.clone(),
                (None, true) => name.clone(),
                (None, false) => format!("{name}<{}>", parameters.iter().map(|parameter| parameter.kotlin(mappings)).collect::<Vec<_>>().join(", ")),
            },
            Self::List(inner) => format!("List<{}>", inner.kotlin(mappings)),
            Self::Optional(inner) => format!("{}?", inner.kotlin(mappings)),
            Self::Map(key, value) => format!("HashMap<{}, {}>", key.kotlin(mappings), value.kotlin(mappings)),
            Self::String | Self::Char => "String".into(),
            Self::Bool => "Boolean".into(),
            Self::I8 => "Byte".into(),
            Self::I16 => "Short".into(),
            Self::I32 => "Int".into(),
            Self::U8 => "UByte".into(),
            Self::U16 => "UShort".into(),
            Self::U32 => "UInt".into(),
            Self::F32 => "Float".into(),
            Self::F64 => "Double".into(),
        }
    }
}

#[derive(Clone)]
struct Name {
    original: String,
    renamed: String,
}

#[derive(Clone)]
struct Field {
    name: Name,
    ty: Type,
    comments: Vec<String>,
    has_default: bool,
}

impl Field {
    fn is_nullable(&self) -> bool {
        self.has_default && !self.ty.is_optional()
    }
}

#[derive(Clone)]
enum Variant {
    Unit { name: Name, comments: Vec<String> },
    Value { name: Name, comments: Vec<String>, ty: Type },
}

impl Variant {
    fn name(&self) -> &Name {
        match self {
            Self::Unit { name, .. } | Self::Value { name, .. } => name,
        }
    }

    fn comments(&self) -> &[String] {
        match self {
            Self::Unit { comments, .. } | Self::Value { comments, .. } => comments,
        }
    }
}

#[derive(Clone)]
enum Shape {
    Record(Vec<Field>),
    Choice(Vec<Variant>),
    Tagged { variants: Vec<Variant>, tag: String, content: String },
}

#[derive(Clone)]
struct Model {
    name: Name,
    comments: Vec<String>,
    conformances: BTreeSet<String>,
    shape: Shape,
}

impl Model {
    fn is_recursive(&self) -> bool {
        match &self.shape {
            Shape::Tagged { variants, .. } => variants.iter().any(|variant| match variant {
                Variant::Value { ty, .. } => ty.contains(&self.name.original),
                Variant::Unit { .. } => false,
            }),
            Shape::Record(_) | Shape::Choice(_) => false,
        }
    }
}

pub struct GeneratedModels {
    pub files: Vec<(PathBuf, String)>,
    pub stale: Vec<PathBuf>,
}

pub fn generate(root: &Path, platform: Platform, output: &Path, mappings: &TypeMappings) -> GeneratedModels {
    let sources = root.join(crate::remote_mappers::PRIMITIVES_SOURCE);
    let directory = output.join(match platform {
        Platform::IOS => SWIFT_DIRECTORY,
        Platform::Android => KOTLIN_DIRECTORY,
    });
    let files = source_files(&sources)
        .into_iter()
        .filter_map(|path| {
            let relative = path.strip_prefix(&sources).expect("source file outside primitives").to_path_buf();
            let file_name = relative.file_name()?.to_str()?.to_string();
            let source = fs::read_to_string(&path).expect("failed to read source file");
            match !SKIPPED_FILES.contains(&file_name.as_str()) && source.contains(DERIVE) {
                true => Some((relative.clone(), parse(&source).unwrap_or_else(|error| panic!("{}: {error}", relative.display())))),
                false => None,
            }
        })
        .filter(|(_, models)| !models.is_empty())
        .map(|(relative, models)| {
            let folders = relative.parent().map(|parent| parent.iter().map(|folder| folder.to_string_lossy().to_string()).collect::<Vec<_>>()).unwrap_or_default();
            let stem = relative.file_stem().expect("source file name").to_string_lossy().split('_').map(capitalized).collect::<String>();
            match platform {
                Platform::IOS => (
                    directory.join(folders.iter().map(|folder| capitalized(folder)).collect::<PathBuf>()).join(format!("{stem}.swift")),
                    swift_file(&models, mappings),
                ),
                Platform::Android => {
                    let package = [KOTLIN_PACKAGE.to_string()].into_iter().chain(folders.iter().map(|folder| folder.to_lowercase())).collect::<Vec<_>>().join(".");
                    (
                        directory.join(folders.iter().map(|folder| folder.to_lowercase()).collect::<PathBuf>()).join(format!("{stem}.kt")),
                        kotlin_file(&models, &package, mappings),
                    )
                }
            }
        })
        .collect::<Vec<_>>();
    let stale = source_files(&directory).into_iter().filter(|path| !files.iter().any(|(generated, _)| generated == path)).collect();
    GeneratedModels { files, stale }
}

fn source_files(directory: &Path) -> Vec<PathBuf> {
    fs::read_dir(directory)
        .map(|entries| entries.filter_map(|entry| entry.ok().map(|entry| entry.path())).collect::<BTreeSet<_>>())
        .unwrap_or_default()
        .into_iter()
        .flat_map(|path| match (path.is_dir(), path.extension().and_then(|extension| extension.to_str())) {
            (true, _) => source_files(&path),
            (false, Some("rs" | "swift" | "kt")) => vec![path],
            (false, _) => vec![],
        })
        .collect()
}

fn capitalized(text: &str) -> String {
    text.chars()
        .enumerate()
        .map(|(index, character)| match index {
            0 => character.to_uppercase().to_string(),
            _ => character.to_string(),
        })
        .collect()
}

fn swift_file(models: &[Model], mappings: &TypeMappings) -> String {
    format!("{HEADER}import Foundation\n{}", models.iter().map(|model| swift_model(model, &mappings.swift)).collect::<Vec<_>>().concat())
}

fn kotlin_file(models: &[Model], package: &str, mappings: &TypeMappings) -> String {
    format!(
        "{HEADER}package {package}\n\nimport kotlinx.serialization.Serializable\nimport kotlinx.serialization.SerialName\n\n{}",
        models.iter().map(|model| kotlin_model(model, &mappings.kotlin)).collect::<Vec<_>>().concat()
    )
}

fn parse(source: &str) -> Result<Vec<Model>, String> {
    let file = syn::parse_file(source).map_err(|error| error.to_string())?;
    let items = marked_items(&file.items)?;
    let records = items
        .iter()
        .filter_map(|item| match item {
            Item::Struct(item) => Some(parse_struct(item)),
            _ => None,
        })
        .collect::<Result<Vec<_>, _>>()?;
    let enums = items
        .iter()
        .filter_map(|item| match item {
            Item::Enum(item) => Some(parse_enum(item)),
            _ => None,
        })
        .collect::<Result<Vec<_>, _>>()?;
    Ok(dependency_order([sorted(records), sorted(enums)].concat()))
}

fn sorted(models: Vec<Model>) -> Vec<Model> {
    models.into_iter().map(|model| (model.name.original.clone(), model)).collect::<BTreeMap<_, _>>().into_values().collect()
}

fn marked_items(items: &[Item]) -> Result<Vec<Item>, String> {
    items
        .iter()
        .map(|item| match item {
            Item::Mod(module) => module.content.as_ref().map(|(_, items)| marked_items(items)).unwrap_or(Ok(vec![])),
            Item::Struct(item) if is_app_model(&item.attrs) => Ok(vec![Item::Struct(item.clone())]),
            Item::Enum(item) if is_app_model(&item.attrs) => Ok(vec![Item::Enum(item.clone())]),
            Item::Type(item) if is_app_model(&item.attrs) => Err(format!("{}: type aliases are not supported", item.ident)),
            _ => Ok(vec![]),
        })
        .collect::<Result<Vec<_>, _>>()
        .map(|items| items.concat())
}

pub(crate) fn is_app_model(attrs: &[Attribute]) -> bool {
    attrs
        .iter()
        .filter(|attr| attr.path().is_ident("derive"))
        .filter_map(|attr| attr.parse_args_with(Punctuated::<syn::Path, Token![,]>::parse_terminated).ok())
        .any(|derives| derives.iter().any(|derive| derive.is_ident(DERIVE)))
}

fn parse_struct(item: &syn::ItemStruct) -> Result<Model, String> {
    let context = item.ident.to_string();
    if value_of(&item.attrs, MARKER, "serialized_as").is_some() {
        return Err(format!("{context}: serialized_as on a type is not supported"));
    }
    if value_of(&item.attrs, "serde", "rename").is_some() {
        return Err(format!("{context}: serde(rename) on a type is not supported"));
    }
    let rename_all = value_of(&item.attrs, "serde", "rename_all");
    let fields = match &item.fields {
        Fields::Named(fields) => fields
            .named
            .iter()
            .filter(|field| !is_skipped(&field.attrs))
            .map(|field| parse_field(&context, field, &rename_all))
            .collect::<Result<Vec<_>, _>>()?,
        Fields::Unit => vec![],
        Fields::Unnamed(_) => return Err(format!("{context}: tuple structs are not supported")),
    };
    Ok(Model {
        name: name_of(&item.ident, &item.attrs, &None),
        comments: comments_of(&item.attrs),
        conformances: swift_conformances(&item.attrs),
        shape: Shape::Record(fields),
    })
}

fn parse_field(context: &str, field: &syn::Field, rename_all: &Option<String>) -> Result<Field, String> {
    let ident = field.ident.as_ref().ok_or_else(|| format!("{context}: unnamed field"))?;
    if has_flag(&field.attrs, "serde", "flatten") {
        return Err(format!("{context}.{ident}: serde(flatten) is not supported"));
    }
    Ok(Field {
        name: name_of(ident, &field.attrs, rename_all),
        ty: field_type(&field.attrs, &field.ty).map_err(|error| format!("{context}.{ident}: {error}"))?,
        comments: comments_of(&field.attrs),
        has_default: has_flag(&field.attrs, "serde", "default"),
    })
}

fn field_type(attrs: &[Attribute], ty: &syn::Type) -> Result<Type, String> {
    match value_of(attrs, MARKER, "serialized_as") {
        Some(serialized) => Type::parse(&syn::parse_str(&serialized).map_err(|error| error.to_string())?),
        None => Type::parse(ty),
    }
}

fn parse_enum(item: &syn::ItemEnum) -> Result<Model, String> {
    let context = item.ident.to_string();
    if value_of(&item.attrs, MARKER, "serialized_as").is_some() {
        return Err(format!("{context}: serialized_as on a type is not supported"));
    }
    if value_of(&item.attrs, "serde", "rename").is_some() {
        return Err(format!("{context}: serde(rename) on a type is not supported"));
    }
    let rename_all = value_of(&item.attrs, "serde", "rename_all");
    let variants = item
        .variants
        .iter()
        .filter(|variant| !is_skipped(&variant.attrs))
        .map(|variant| parse_variant(&context, variant, &rename_all))
        .collect::<Result<Vec<_>, _>>()?;
    let tag = value_of(&item.attrs, "serde", "tag");
    let content = value_of(&item.attrs, "serde", "content");
    let is_choice = variants.iter().all(|variant| match variant {
        Variant::Unit { .. } => true,
        Variant::Value { .. } => false,
    });
    let shape = match (is_choice, tag, content) {
        (true, None, None) => Shape::Choice(variants),
        (true, _, _) => return Err(format!("{context}: serde tag and content need a variant with data")),
        (false, Some(tag), Some(content)) => Shape::Tagged { variants, tag, content },
        (false, _, _) => return Err(format!("{context}: a variant with data needs serde tag and content")),
    };
    Ok(Model {
        name: name_of(&item.ident, &item.attrs, &None),
        comments: comments_of(&item.attrs),
        conformances: swift_conformances(&item.attrs),
        shape,
    })
}

fn parse_variant(context: &str, variant: &syn::Variant, rename_all: &Option<String>) -> Result<Variant, String> {
    let name = name_of(&variant.ident, &variant.attrs, rename_all);
    let comments = comments_of(&variant.attrs);
    match &variant.fields {
        Fields::Unit => Ok(Variant::Unit { name, comments }),
        Fields::Unnamed(fields) => match fields.unnamed.iter().collect::<Vec<_>>().as_slice() {
            [field] => Ok(Variant::Value {
                name,
                comments,
                ty: field_type(&field.attrs, &field.ty).map_err(|error| format!("{context}::{}: {error}", variant.ident))?,
            }),
            _ => Err(format!("{context}::{}: a variant carries one value", variant.ident)),
        },
        Fields::Named(_) => Err(format!("{context}::{}: struct variants are not supported", variant.ident)),
    }
}

fn arguments(attr: &Attribute, namespace: &str) -> Vec<Meta> {
    match attr.path().is_ident(namespace) {
        true => attr.parse_args_with(Punctuated::<Meta, Token![,]>::parse_terminated).map(|arguments| arguments.into_iter().collect()).unwrap_or_default(),
        false => vec![],
    }
}

fn values_of(attrs: &[Attribute], namespace: &str, key: &str) -> Vec<String> {
    attrs
        .iter()
        .flat_map(|attr| arguments(attr, namespace))
        .filter_map(|argument| match argument {
            Meta::NameValue(pair) if pair.path.is_ident(key) => string_of(&pair.value),
            _ => None,
        })
        .collect()
}

fn value_of(attrs: &[Attribute], namespace: &str, key: &str) -> Option<String> {
    values_of(attrs, namespace, key).into_iter().next()
}

fn has_flag(attrs: &[Attribute], namespace: &str, flag: &str) -> bool {
    attrs.iter().flat_map(|attr| arguments(attr, namespace)).any(|argument| match argument {
        Meta::Path(path) => path.is_ident(flag),
        _ => false,
    })
}

fn is_skipped(attrs: &[Attribute]) -> bool {
    has_flag(attrs, "serde", "skip") || has_flag(attrs, MARKER, "skip")
}

fn string_of(expr: &Expr) -> Option<String> {
    match expr {
        Expr::Lit(ExprLit { lit: Lit::Str(text), .. }) => Some(text.value().trim().to_string()),
        _ => None,
    }
}

fn comments_of(attrs: &[Attribute]) -> Vec<String> {
    attrs
        .iter()
        .filter_map(|attr| match &attr.meta {
            Meta::NameValue(pair) if pair.path.is_ident("doc") => string_of(&pair.value),
            _ => None,
        })
        .collect()
}

fn swift_conformances(attrs: &[Attribute]) -> BTreeSet<String> {
    values_of(attrs, MARKER, "swift").iter().flat_map(|value| value.split(',').map(|conformance| conformance.trim().to_string())).collect()
}

fn name_of(ident: &syn::Ident, attrs: &[Attribute], rename_all: &Option<String>) -> Name {
    let original = ident.to_string().replace("r#", "");
    let renamed = value_of(attrs, "serde", "rename").unwrap_or_else(|| rename_case(&original, rename_all));
    Name { original, renamed }
}

fn rename_case(original: &str, rename_all: &Option<String>) -> String {
    match rename_all.as_deref() {
        Some("lowercase") => original.to_lowercase(),
        Some("UPPERCASE") => original.to_uppercase(),
        Some("PascalCase") => pascal_case(original),
        Some("camelCase") => camel_case(original),
        Some("snake_case") => snake_case(original),
        Some("SCREAMING_SNAKE_CASE") => snake_case(original).to_ascii_uppercase(),
        Some("kebab-case") => snake_case(original).replace('_', "-"),
        Some("SCREAMING-KEBAB-CASE") => snake_case(original).replace('_', "-").to_ascii_uppercase(),
        _ => original.to_string(),
    }
}

fn pascal_case(name: &str) -> String {
    let uppercase = name.to_ascii_uppercase() == name;
    name.chars()
        .fold((String::new(), true), |(text, capitalize), character| match (character, capitalize) {
            ('_', _) => (text, true),
            (character, true) => (format!("{text}{}", character.to_ascii_uppercase()), false),
            (character, false) if uppercase => (format!("{text}{}", character.to_ascii_lowercase()), false),
            (character, false) => (format!("{text}{character}"), false),
        })
        .0
}

fn camel_case(name: &str) -> String {
    let pascal = pascal_case(name);
    format!("{}{}", pascal[..1].to_ascii_lowercase(), &pascal[1..])
}

fn snake_case(name: &str) -> String {
    let uppercase = name.to_ascii_uppercase() == name;
    name.char_indices()
        .map(|(index, character)| match index > 0 && character.is_uppercase() && !uppercase {
            true => format!("_{}", character.to_ascii_lowercase()),
            false => character.to_ascii_lowercase().to_string(),
        })
        .collect()
}

fn variant_identifier(name: &str) -> String {
    match name.starts_with(|character: char| character.is_ascii_digit()) {
        true => format!("_{name}"),
        false => name.to_string(),
    }
}

fn swift_identifier(name: &str) -> String {
    match SWIFT_KEYWORDS.contains(&name) {
        true => format!("`{name}`"),
        false => name.to_string(),
    }
}

fn undashed(name: &str) -> String {
    name.replace('-', "_")
}

fn swift_comments(indent: usize, comments: &[String]) -> String {
    comments.iter().map(|comment| format!("{}/// {}\n", "\t".repeat(indent), comment.trim_end())).collect()
}

fn kotlin_comments(indent: usize, comments: &[String]) -> String {
    comments.iter().map(|comment| format!("{}/// {comment}\n", "\t".repeat(indent))).collect()
}

fn swift_model(model: &Model, mappings: &BTreeMap<String, String>) -> String {
    let name = swift_identifier(&model.name.renamed);
    let declared = |always: &[&str]| {
        always
            .iter()
            .map(|conformance| conformance.to_string())
            .chain(model.conformances.iter().filter(|conformance| !always.contains(&conformance.as_str())).cloned())
            .collect::<Vec<_>>()
            .join(", ")
    };
    let indirect = if model.is_recursive() { "indirect " } else { "" };
    match &model.shape {
        Shape::Record(fields) => format!(
            "\n{}public struct {name}: {} {{\n{}{}{}\tpublic init({}) {{{}{}}}\n}}\n",
            swift_comments(0, &model.comments),
            declared(&["Codable"]),
            fields
                .iter()
                .map(|field| format!(
                    "{}\tpublic let {}: {}{}\n",
                    swift_comments(1, &field.comments),
                    undashed(&swift_identifier(&field.name.renamed)),
                    field.ty.swift(mappings),
                    if field.is_nullable() { "?" } else { "" }
                ))
                .collect::<String>(),
            swift_coding_keys(fields),
            if fields.is_empty() { "" } else { "\n" },
            fields
                .iter()
                .map(|field| format!("{}: {}{}", undashed(&field.name.renamed), field.ty.swift(mappings), if field.is_nullable() { "?" } else { "" }))
                .collect::<Vec<_>>()
                .join(", "),
            fields
                .iter()
                .map(|field| format!("\n\t\tself.{} = {}", undashed(&field.name.renamed), undashed(&swift_identifier(&field.name.renamed))))
                .collect::<String>(),
            if fields.is_empty() { "" } else { "\n\t" },
        ),
        Shape::Choice(variants) => format!(
            "\n{}public {indirect}enum {name}: {} {{\n{}}}\n",
            swift_comments(0, &model.comments),
            declared(&["String", "Codable"]),
            variants
                .iter()
                .map(|variant| {
                    let case_name = camel_case(&variant.name().original);
                    let raw_value = match variant.name().renamed == case_name {
                        true => String::new(),
                        false => format!(" = {:?}", variant.name().renamed),
                    };
                    format!("{}\tcase {}{raw_value}\n", swift_comments(1, variant.comments()), swift_identifier(&case_name))
                })
                .collect::<String>()
        ),
        Shape::Tagged { variants, tag, content } => swift_tagged(model, &name, &declared(&["Codable"]), indirect, variants, tag, content, mappings),
    }
}

fn swift_coding_keys(fields: &[Field]) -> String {
    match fields.iter().any(|field| field.name.renamed.contains('-')) {
        true => format!(
            "\n\tenum CodingKeys: String, CodingKey, Codable {{\n\t\tcase {}\n\t}}\n",
            fields
                .iter()
                .map(|field| match field.name.renamed.contains('-') {
                    true => format!("{} = \"{}\"", undashed(&swift_identifier(&field.name.renamed)), field.name.renamed),
                    false => undashed(&swift_identifier(&field.name.renamed)),
                })
                .collect::<Vec<_>>()
                .join(",\n\t\t\t")
        ),
        false => String::new(),
    }
}

#[allow(clippy::too_many_arguments)]
fn swift_tagged(model: &Model, name: &str, declared: &str, indirect: &str, variants: &[Variant], tag: &str, content: &str, mappings: &BTreeMap<String, String>) -> String {
    let cases = variants
        .iter()
        .map(|variant| {
            let case_name = variant_identifier(&camel_case(&variant.name().original));
            let key = match case_name == variant.name().renamed {
                true => swift_identifier(&case_name),
                false => format!("{} = \"{}\"", swift_identifier(&case_name), variant.name().renamed),
            };
            let (declaration, decoding, encoding) = match variant {
                Variant::Unit { .. } => (
                    format!("\tcase {}\n", swift_identifier(&case_name)),
                    format!("\n\t\t\tcase .{case_name}:\n\t\t\t\tself = .{case_name}\n\t\t\t\treturn"),
                    format!("\n\t\tcase .{0}:\n\t\t\ttry container.encode(CodingKeys.{0}, forKey: .{tag})", swift_identifier(&case_name)),
                ),
                Variant::Value { ty, .. } => {
                    let case_type = swift_identifier(&ty.swift(mappings));
                    let decoding = match ty.is_optional() {
                        true => format!(
                            "\n            case .{case_name}:\n\t\t\t\tif let content = try? container.decode({case_type}.self, forKey: .{content}) {{\n\t\t\t\t\tself = .{case_name}(content)\n\t\t\t\t\treturn\n\t\t\t\t}}\n\t\t\t\telse if let isNil = try? container.decodeNil(forKey: .{content}), isNil {{\n\t\t\t\t\tself = .{case_name}(nil)\n\t\t\t\t\treturn\n\t\t\t\t}}"
                        ),
                        false => format!(
                            "\n\t\t\tcase .{case_name}:\n\t\t\t\tif let content = try? container.decode({case_type}.self, forKey: .{content}) {{\n\t\t\t\t\tself = .{case_name}(content)\n\t\t\t\t\treturn\n\t\t\t\t}}"
                        ),
                    };
                    (
                        format!("\tcase {}({case_type})\n", swift_identifier(&case_name)),
                        decoding,
                        format!("\n\t\tcase .{case_name}(let content):\n\t\t\ttry container.encode(CodingKeys.{case_name}, forKey: .{tag})\n\t\t\ttry container.encode(content, forKey: .{content})"),
                    )
                }
            };
            (format!("{}{declaration}", swift_comments(1, variant.comments())), key, decoding, encoding)
        })
        .collect::<Vec<_>>();
    let declarations = cases.iter().map(|(declaration, ..)| declaration.as_str()).collect::<String>();
    let keys = cases.iter().map(|(_, key, ..)| key.as_str()).collect::<Vec<_>>().join(",\n\t\t\t");
    let decoding = cases.iter().map(|(_, _, decoding, _)| decoding.as_str()).collect::<String>();
    let encoding = cases.iter().map(|(.., encoding)| encoding.as_str()).collect::<String>();
    let coding_keys = match cases.is_empty() {
        true => String::new(),
        false => format!("\n\tenum CodingKeys: String, CodingKey, Codable {{\n\t\tcase {keys}\n\t}}\n"),
    };
    format!(
        "\n{}public {indirect}enum {name}: {declared} {{\n{declarations}{coding_keys}\n\tprivate enum ContainerCodingKeys: String, CodingKey {{\n\t\tcase {tag}, {content}\n\t}}\n\n\tpublic init(from decoder: Decoder) throws {{\n\t\tlet container = try decoder.container(keyedBy: ContainerCodingKeys.self)\n\t\tif let type = try? container.decode(CodingKeys.self, forKey: .{tag}) {{\n\t\t\tswitch type {{{decoding}\n\t\t\t}}\n\t\t}}\n\t\tthrow DecodingError.typeMismatch({name}.self, DecodingError.Context(codingPath: decoder.codingPath, debugDescription: \"Wrong type for {name}\"))\n\t}}\n\n\tpublic func encode(to encoder: Encoder) throws {{\n\t\tvar container = encoder.container(keyedBy: ContainerCodingKeys.self)\n\t\tswitch self {{{encoding}\n\t\t}}\n\t}}\n}}\n",
        swift_comments(0, &model.comments),
    )
}

fn kotlin_model(model: &Model, mappings: &BTreeMap<String, String>) -> String {
    let comments = kotlin_comments(0, &model.comments);
    match &model.shape {
        Shape::Record(fields) if fields.is_empty() => format!("{comments}@Serializable\nobject {}\n\n", model.name.renamed),
        Shape::Record(fields) => {
            let serial_names = fields.iter().any(|field| field.name.renamed.contains('-'));
            format!(
                "{comments}@Serializable\ndata class {} (\n{}\n)\n\n",
                model.name.renamed,
                fields
                    .iter()
                    .map(|field| format!(
                        "{}{}\tval {}: {}{}",
                        kotlin_comments(1, &field.comments),
                        if serial_names { format!("\t@SerialName({:?})\n", field.name.renamed) } else { String::new() },
                        undashed(&field.name.renamed),
                        field.ty.kotlin(mappings),
                        match (field.is_nullable(), field.ty.is_optional()) {
                            (true, _) => "? = null",
                            (false, true) => " = null",
                            (false, false) => "",
                        }
                    ))
                    .collect::<Vec<_>>()
                    .join(",\n")
            )
        }
        Shape::Choice(variants) => format!(
            "{comments}@Serializable\nenum class {}(val string: String) {{\n{}}}\n\n",
            model.name.renamed,
            variants
                .iter()
                .map(|variant| format!(
                    "{}\t@SerialName({:?})\n\t{}({:?}),\n",
                    kotlin_comments(1, variant.comments()),
                    variant.name().renamed,
                    variant.name().original,
                    variant.name().renamed
                ))
                .collect::<String>()
        ),
        Shape::Tagged { variants, content, .. } => format!(
            "{comments}@Serializable\nsealed class {} {{\n{}}}\n\n",
            model.name.renamed,
            variants
                .iter()
                .map(|variant| {
                    let class_name = variant_identifier(&pascal_case(&variant.name().original));
                    let declaration = match variant {
                        Variant::Unit { .. } => format!("\tobject {class_name}"),
                        Variant::Value { ty, .. } => format!("\tdata class {class_name}(val {content}: {})", ty.kotlin(mappings)),
                    };
                    format!(
                        "{}\t@Serializable\n\t@SerialName(\"{}\")\n{declaration}: {}()\n",
                        kotlin_comments(1, variant.comments()),
                        variant.name().renamed,
                        model.name.original
                    )
                })
                .collect::<String>()
        ),
    }
}

struct Walk {
    found: Vec<String>,
    seen: HashSet<String>,
}

impl Walk {
    fn insert(self, name: &str) -> (Self, bool) {
        match self.seen.contains(name) {
            true => (self, false),
            false => (
                Self {
                    seen: self.seen.into_iter().chain([name.to_string()]).collect(),
                    ..self
                },
                true,
            ),
        }
    }

    fn remove(self, name: &str) -> Self {
        Self {
            seen: self.seen.into_iter().filter(|seen| seen != name).collect(),
            ..self
        }
    }

    fn found(self, name: &str) -> Self {
        Self {
            found: [self.found, vec![name.to_string()]].concat(),
            ..self
        }
    }
}

fn type_dependencies(ty: &Type, models: &HashMap<String, &Model>, walk: Walk) -> Walk {
    let walk = match ty {
        Type::Named(name, parameters) => match models.get(name) {
            Some(model) => match walk.insert(name) {
                (walk, true) => {
                    let walk = model_dependencies(model, models, walk.found(name));
                    let walk = parameters.iter().fold(walk, |walk, parameter| match parameter {
                        Type::Named(parameter, _) => match models.get(parameter) {
                            Some(dependency) => match walk.insert(parameter) {
                                (walk, true) => model_dependencies(dependency, models, walk.found(parameter)).remove(parameter),
                                (walk, false) => walk,
                            },
                            None => walk,
                        },
                        _ => walk,
                    });
                    walk.remove(name)
                }
                (walk, false) => walk,
            },
            None => walk,
        },
        Type::Map(key, value) => type_dependencies(value, models, type_dependencies(key, models, walk)),
        Type::Optional(inner) | Type::List(inner) => type_dependencies(inner, models, walk),
        _ => walk,
    };
    match ty {
        Type::Named(name, _) => walk.remove(name),
        _ => walk,
    }
}

fn model_dependencies(model: &Model, models: &HashMap<String, &Model>, walk: Walk) -> Walk {
    let name = model.name.original.as_str();
    match &model.shape {
        Shape::Choice(_) => walk,
        Shape::Record(fields) => match walk.insert(name) {
            (walk, true) => fields.iter().fold(walk, |walk, field| type_dependencies(&field.ty, models, walk)).remove(name),
            (walk, false) => walk,
        },
        Shape::Tagged { variants, .. } => match walk.insert(name) {
            (walk, true) => variants
                .iter()
                .fold(walk.found(name), |walk, variant| match variant {
                    Variant::Value { ty, .. } => type_dependencies(ty, models, walk),
                    Variant::Unit { .. } => walk,
                })
                .remove(name),
            (walk, false) => walk,
        },
    }
}

struct Order {
    order: Vec<usize>,
    processed: Vec<usize>,
    visiting: Vec<usize>,
    stopped: bool,
}

fn visit(graph: &[Vec<usize>], nodes: &[usize], state: Order) -> Order {
    nodes.iter().fold(Order { stopped: false, ..state }, |state, &node| match state.stopped || state.processed.contains(&node) {
        true => state,
        false => match state.visiting.contains(&node) {
            true => Order { stopped: true, ..state },
            false => {
                let visited = visit(
                    graph,
                    &graph[node],
                    Order {
                        visiting: [state.visiting, vec![node]].concat(),
                        ..state
                    },
                );
                Order {
                    order: [visited.order, vec![node]].concat(),
                    processed: [visited.processed, vec![node]].concat(),
                    visiting: visited.visiting.into_iter().filter(|visiting| *visiting != node).collect(),
                    stopped: false,
                }
            }
        },
    })
}

fn dependency_order(models: Vec<Model>) -> Vec<Model> {
    let by_name = models.iter().map(|model| (model.name.original.clone(), model)).collect::<HashMap<_, _>>();
    let graph = models
        .iter()
        .map(|model| {
            model_dependencies(model, &by_name, Walk { found: vec![], seen: HashSet::new() })
                .found
                .iter()
                .filter_map(|dependency| models.iter().position(|model| model.name.original == *dependency))
                .collect::<Vec<_>>()
        })
        .collect::<Vec<_>>();
    let order = visit(
        &graph,
        &(0..models.len()).collect::<Vec<_>>(),
        Order {
            order: vec![],
            processed: vec![],
            visiting: vec![],
            stopped: false,
        },
    )
    .order;
    order.iter().map(|&index| models[index].clone()).collect()
}

