use config::{File, FileFormat};
use serde::Deserialize;
use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

pub const HEADER: &str = "// Generated by `just generate-models`. Do not edit.\n// Declared in core/bin/generate/remote_types.yml.\n";
pub const REMOTE_TYPES_PATH: &str = "gemstone/src/models/remote_types.rs";
pub const PRIMITIVES_SOURCE: &str = "crates/primitives/src";
const CONFIG: &str = include_str!("../remote_types.yml");

/// `remote_types.yml`: the types that cross, and every type name the generator has to know.
#[derive(Deserialize)]
pub struct Config {
    remote: Vec<String>,
    codes: Vec<String>,
    identifiers: Vec<String>,
    scalars: Vec<String>,
    declared: BTreeMap<String, String>,
    #[serde(default)]
    conversions: BTreeMap<String, BTreeMap<String, Vec<String>>>,
    #[serde(default)]
    defaults: BTreeMap<String, String>,
    #[serde(default)]
    mocks: Vec<Mock>,
}

/// A `mocks:` entry: a type name, or a type name with the values of the fields the default rules
/// would build invalid.
#[derive(Deserialize)]
#[serde(untagged)]
enum Mock {
    Plain(String),
    Overridden(BTreeMap<String, BTreeMap<String, String>>),
}

impl Config {
    pub fn from_yaml(yaml: &str) -> Self {
        config::Config::builder()
            .add_source(File::from_str(yaml, FileFormat::Yaml))
            .build()
            .and_then(|config| config.try_deserialize())
            .expect("remote_types.yml is malformed")
    }

    fn is_scalar(&self, name: &str) -> bool {
        self.scalars.iter().any(|scalar| scalar == name)
    }

    /// A type gemstone declares under another name, such as a big integer or a date.
    fn declared(&self, name: &str) -> Option<&str> {
        self.declared.get(name).map(String::as_str)
    }

    /// The expression that converts a declared type the app spells differently, per language and direction.
    fn conversion(&self, name: &str, language: &str, index: usize) -> Option<&str> {
        self.conversions.get(name)?.get(language)?.get(index).map(String::as_str)
    }

    /// The variant a skipped enum field falls back to, since the app type does not carry one.
    fn default_variant(&self, name: &str) -> Option<&str> {
        self.defaults.get(name).map(String::as_str)
    }

    /// The declared names that are gemstone custom types, which the declarations import.
    fn mocked(&self) -> Vec<&str> {
        self.mocks
            .iter()
            .flat_map(|mock| match mock {
                Mock::Plain(name) => vec![name.as_str()],
                Mock::Overridden(types) => types.keys().map(String::as_str).collect(),
            })
            .collect()
    }

    fn mock_override(&self, record: &str, field: &str) -> Option<&str> {
        self.mocks.iter().find_map(|mock| match mock {
            Mock::Plain(_) => None,
            Mock::Overridden(types) => types.get(record)?.get(field).map(String::as_str),
        })
    }

    fn custom_types<'a>(&'a self, types: &'a [RemoteType]) -> Vec<&'a str> {
        self.declared
            .iter()
            .filter(|(rust, declared)| !declared.contains("::") && types.iter().any(|remote| remote.field_types().iter().any(|type_name| unwrap(type_name).0 == rust.as_str())))
            .map(|(_, declared)| declared.as_str())
            .collect()
    }
}

pub enum RemoteType {
    Enum {
        name: String,
        module: String,
        variants: Vec<Variant>,
        typeshared: bool,
        content: Option<String>,
    },
    Record {
        name: String,
        module: String,
        fields: Vec<Field>,
        typeshared: bool,
    },
    Code {
        name: String,
    },
}

pub struct Variant {
    name: String,
    fields: Vec<Field>,
}

pub struct Field {
    rust: String,
    serialized: String,
    type_name: String,
    skipped: bool,
}

impl RemoteType {
    fn name(&self) -> &str {
        match self {
            Self::Enum { name, .. } | Self::Record { name, .. } | Self::Code { name } => name,
        }
    }

    fn module(&self) -> &str {
        match self {
            Self::Enum { module, .. } | Self::Record { module, .. } => module,
            Self::Code { .. } => "",
        }
    }

    fn typeshared(&self) -> bool {
        match self {
            Self::Enum { typeshared, .. } | Self::Record { typeshared, .. } => *typeshared,
            Self::Code { .. } => true,
        }
    }

    fn field_types(&self) -> Vec<&str> {
        match self {
            Self::Enum { variants, .. } => variants.iter().flat_map(|variant| variant.fields.iter().map(|field| field.type_name.as_str())).collect(),
            Self::Record { fields, .. } => fields.iter().map(|field| field.type_name.as_str()).collect(),
            Self::Code { .. } => Vec::new(),
        }
    }
}

/// The remote types declared in `remote_types.yml`, read once from the primitives sources.
pub struct Generator {
    config: Config,
    types: Vec<RemoteType>,
    mocked: Vec<RemoteType>,
    app_types: BTreeMap<String, AppType>,
}

/// A TypeShare declaration as the apps see it: its module, and for an enum its variants.
struct AppType {
    module: String,
    variants: Option<Vec<Variant>>,
}

impl Generator {
    pub fn load(root: &Path) -> Self {
        Self::parse(Config::from_yaml(CONFIG), &root.join(PRIMITIVES_SOURCE))
    }

    pub fn parse(config: Config, primitives: &Path) -> Self {
        let mut found = Vec::new();
        let mut mocked = Vec::new();
        let mut app_types = BTreeMap::new();
        let mocks = config.mocked();
        for path in source_files(primitives) {
            let Ok(source) = fs::read_to_string(&path) else { continue };
            let module = path
                .strip_prefix(primitives)
                .ok()
                .and_then(Path::parent)
                .map(|parent| parent.components().map(|component| component.as_os_str().to_string_lossy().into_owned()).collect::<Vec<_>>().join("."))
                .unwrap_or_default();
            let mut lines = source.lines();
            let mut typeshare = false;
            let mut camel_case_fields = false;
            let mut content = None;
            while let Some(line) = lines.next() {
                let Some((keyword, name)) = declaration(line.trim()) else {
                    let attribute = line.trim().starts_with("#[");
                    typeshare = attribute && (typeshare || line.trim().starts_with("#[typeshare"));
                    camel_case_fields = attribute && (camel_case_fields || line.trim() == "#[serde(rename_all = \"camelCase\")]");
                    content = attribute.then(|| content.take().or_else(|| serde_content(line.trim()))).flatten();
                    continue;
                };
                let declared = std::mem::take(&mut typeshare);
                let camel = std::mem::take(&mut camel_case_fields);
                let tagged_content = content.take();
                let remote = config.remote.contains(&name);
                let mock = declared && keyword == "struct" && mocks.contains(&name.as_str());
                if !declared && !remote {
                    continue;
                }
                let body = body(&mut lines);
                if declared {
                    let variants = (keyword == "enum").then(|| variants(&name, &body));
                    app_types.insert(name.clone(), AppType { module: module.clone(), variants });
                }
                if mock {
                    mocked.push(RemoteType::Record {
                        name: name.clone(),
                        module: module.clone(),
                        fields: fields(&body, camel),
                        typeshared: declared,
                    });
                }
                if config.codes.contains(&name) {
                    if !declared {
                        continue;
                    }
                    assert_eq!(keyword, "enum", "{name} crosses as a code but is not an enum");
                    found.push(RemoteType::Code { name });
                    continue;
                }
                if !remote {
                    continue;
                }
                found.push(match keyword {
                    "enum" => RemoteType::Enum {
                        variants: variants(&name, &body),
                        name,
                        module: module.clone(),
                        typeshared: declared,
                        content: tagged_content,
                    },
                    _ => RemoteType::Record {
                        name,
                        module: module.clone(),
                        fields: fields(&body, camel),
                        typeshared: declared,
                    },
                });
            }
        }
        for name in config.remote.iter().chain(&config.codes) {
            let typeshared = found.iter().filter(|remote| remote.name() == name && remote.typeshared()).count();
            if typeshared > 0 {
                found.retain(|remote| remote.name() != name || remote.typeshared());
            }
            let declarations = found.iter().filter(|remote| remote.name() == name).count();
            assert!(
                declarations == 1,
                "{name} has {declarations} declarations in {}, expected exactly one TypeShare declaration or one plain one",
                primitives.display()
            );
        }
        for name in &mocks {
            let declarations = mocked.iter().filter(|mock| mock.name() == *name).count();
            assert!(declarations == 1, "{name} is listed under mocks: and has {declarations} TypeShare structs in {}, expected one", primitives.display());
        }
        found.sort_by_key(|remote| (matches!(remote, RemoteType::Record { .. }), remote.name().to_string()));
        mocked.sort_by_key(|mock| mock.name().to_string());
        Self { config, types: found, mocked, app_types }
    }

    pub fn is_empty(&self) -> bool {
        self.types.is_empty()
    }

    /// The `#[uniffi::remote]` declarations gemstone compiles.
    pub fn remote_types(&self) -> String {
        let types = &self.types;
        let mut names = types.iter().map(RemoteType::name).collect::<Vec<_>>();
        names.sort_unstable();
        let mut out = format!("{HEADER}\nuse primitives::{{{}}};\n", names.join(", "));
        if types.iter().any(|remote| matches!(remote, RemoteType::Code { .. })) {
            out.push_str("use std::str::FromStr;\n");
        }
        match self.config.custom_types(types).as_slice() {
            [] => {}
            [single] => out.push_str(&format!("use crate::models::custom_types::{single};\n")),
            many => out.push_str(&format!("use crate::models::custom_types::{{{}}};\n", many.join(", "))),
        }
        for remote in types {
            match remote {
                RemoteType::Code { name } => out.push_str(&format!(
                    "\nuniffi::custom_type!({name}, String, {{\n    remote,\n    lower: |value| value.as_ref().to_string(),\n    try_lift: |value| {name}::from_str(&value).map_err(|_| uniffi::deps::anyhow::Error::msg(\"Invalid {name}\")),\n}});\n"
                )),
                RemoteType::Enum { name, variants, .. } => {
                    out.push_str(&format!("\n#[uniffi::remote(Enum)]\npub enum {name} {{\n"));
                    for variant in variants {
                        if variant.fields.is_empty() {
                            out.push_str(&format!("    {},\n", variant.name));
                            continue;
                        }
                        if variant.fields.iter().all(|field| field.rust.is_empty()) {
                            let types = variant.fields.iter().map(|field| self.declared_type(&field.type_name)).collect::<Vec<_>>();
                            out.push_str(&format!("    {}({}),\n", variant.name, types.join(", ")));
                            continue;
                        }
                        out.push_str(&format!("    {} {{\n", variant.name));
                        for field in &variant.fields {
                            out.push_str(&format!("        {}: {},\n", field.rust, self.declared_type(&field.type_name)));
                        }
                        out.push_str("    },\n");
                    }
                    out.push_str("}\n");
                }
                RemoteType::Record { name, fields, .. } => {
                    out.push_str(&format!("\n#[uniffi::remote(Record)]\npub struct {name} {{\n"));
                    for field in fields {
                        out.push_str(&format!("    pub {}: {},\n", field.rust, self.declared_type(&field.type_name)));
                    }
                    out.push_str("}\n");
                }
            }
        }
        out
    }

    pub fn swift(&self) -> String {
        self.mappers(&SWIFT)
    }

    pub fn kotlin(&self) -> String {
        self.mappers(&KOTLIN)
    }

    pub fn swift_mocks(&self) -> String {
        self.mocks(&SWIFT)
    }

    pub fn kotlin_mocks(&self) -> String {
        self.mocks(&KOTLIN)
    }

    /// One `mock(...)` per type listed under `mocks:`, taking every field with the default the
    /// rules give its type.
    fn mocks(&self, language: &Language) -> String {
        let mut body = String::new();
        let mut imports = Vec::new();
        for mock in &self.mocked {
            let RemoteType::Record { name, fields, .. } = mock else { continue };
            imports.push(name.as_str());
            body.push_str(&language.mock_open.replace("{type}", name).replace("{function}", &uniffi_type_name(name)));
            for field in fields.iter().filter(|field| !field.skipped) {
                imports.extend(self.named_types(language, &field.type_name));
                let value = match self.config.mock_override(name, &field.rust) {
                    Some(value) => self.mock_literal(language, name, field, value),
                    None => self.mock_default(language, name, field),
                };
                body.push_str(
                    &language
                        .mock_parameter
                        .replace("{label}", &field.serialized)
                        .replace("{type}", &self.app_type(language, &field.type_name))
                        .replace("{value}", &value),
                );
            }
            body.push_str(&language.mock_body.replace("{type}", name));
            for field in fields.iter().filter(|field| !field.skipped) {
                body.push_str(&language.field.replace("{label}", &field.serialized).replace("{value}", &field.serialized));
            }
            body.push_str(language.mock_close);
        }
        let mut out = format!("{HEADER}\n{}", language.mock_header);
        if !language.mock_import.is_empty() {
            let mut imports = imports
                .into_iter()
                .map(|name| match self.app_types.get(name).map(|app| app.module.as_str()).unwrap_or_default() {
                    "" => format!("{}.{name}", language.app_module),
                    module => format!("{}.{module}.{name}", language.app_module),
                })
                .collect::<Vec<_>>();
            imports.sort_unstable();
            imports.dedup();
            out.push('\n');
            for import in imports {
                out.push_str(&language.mock_import.replace("{}", &import));
            }
        }
        out.push_str(&body);
        out
    }

    /// The app types a field type names, which a Kotlin mock file imports.
    fn named_types<'a>(&self, language: &Language, type_name: &'a str) -> Vec<&'a str> {
        match unwrap(type_name) {
            (inner, Wrapper::Option | Wrapper::Vec) => self.named_types(language, inner),
            (name, Wrapper::None) if self.app_types.contains_key(name) || self.config.identifiers.iter().any(|identifier| identifier == name) => vec![name],
            (name, Wrapper::None) => language.app_type_imports.iter().filter(|(rust, _)| *rust == name).map(|(_, app)| *app).collect(),
        }
    }

    fn app_type(&self, language: &Language, type_name: &str) -> String {
        match unwrap(type_name) {
            (inner, Wrapper::Option) => language.optional_type.replace("{}", &self.app_type(language, inner)),
            (inner, Wrapper::Vec) => language.list_type.replace("{}", &self.app_type(language, inner)),
            (name, Wrapper::None) => language.app_types.iter().find(|(rust, ..)| *rust == name).map_or(name, |(_, app, _)| app).to_string(),
        }
    }

    fn mock_default(&self, language: &Language, record: &str, field: &Field) -> String {
        let name = match unwrap(&field.type_name) {
            (_, Wrapper::Option) => return language.none.to_string(),
            (_, Wrapper::Vec) => return language.empty_vec.to_string(),
            (name, Wrapper::None) => name,
        };
        if let Some((_, _, zero)) = language.app_types.iter().find(|(rust, ..)| *rust == name) {
            return zero.to_string();
        }
        if self.config.identifiers.iter().any(|identifier| identifier == name) || self.mocked.iter().any(|mock| mock.name() == name) {
            return language.mock_reference.replace("{function}", &uniffi_type_name(name));
        }
        match self.app_types.get(name).and_then(|app| app.variants.as_ref()).and_then(|variants| variants.first()) {
            Some(variant) if variant.fields.is_empty() => language.enum_value.replace("{type}", name).replace("{case}", &(language.cases[1])(&variant.name)),
            Some(variant) => panic!("{record}.{}: the first variant of {name}, {}, carries data; add an override under mocks:", field.rust, variant.name),
            None => panic!("{record}.{}: {name} has no mock and no default rule; list {name} under mocks: or add an override", field.rust),
        }
    }

    /// An override from `mocks:`, written as the field's type spells it: a string is quoted, an
    /// enum names its variant, a number or a flag stays as written.
    fn mock_literal(&self, language: &Language, record: &str, field: &Field, value: &str) -> String {
        let name = match unwrap(&field.type_name) {
            (inner, Wrapper::Option) => inner,
            (_, Wrapper::Vec) => panic!("{record}.{} is a list; a mock override takes a string, number, flag or enum variant", field.rust),
            (name, Wrapper::None) => name,
        };
        match self.app_types.get(name).and_then(|app| app.variants.as_ref()) {
            Some(_) => language.enum_value.replace("{type}", name).replace("{case}", &(language.cases[1])(value)),
            None if name == "String" => format!("{value:?}"),
            None if self.config.is_scalar(name) => value.to_string(),
            None => panic!("{record}.{}: {name} cannot be overridden; a mock override takes a string, number, flag or enum variant", field.rust),
        }
    }

    /// One `map()` / `toPrimitives()` / `toGem()` per direction for every remote type that has a
    /// TypeShare twin; a type without one is held by the apps as the uniffi type itself.
    fn mappers(&self, language: &Language) -> String {
        let mut out = format!("{HEADER}\n{}", language.header);
        for remote in self.types.iter().filter(|remote| remote.typeshared()) {
            let name = remote.name();
            if let RemoteType::Code { .. } = remote {
                out.push_str(&language.code_mapper.replace("{name}", name));
                continue;
            }
            let core_type = format!("{}.{}", language.core_module, uniffi_type_name(name));
            let app_type = match (language.app_modules, remote.module()) {
                (true, module) if !module.is_empty() => format!("{}.{module}.{name}", language.app_module),
                _ => format!("{}.{name}", language.app_module),
            };
            for index in 0..2 {
                let (from, to) = match index {
                    0 => (&core_type, &app_type),
                    _ => (&app_type, &core_type),
                };
                out.push_str(&language.open.replace("{from}", from).replace("{function}", language.functions[index]).replace("{to}", to));
                match remote {
                    RemoteType::Enum { variants, content, .. } => {
                        let sealed = variants.iter().any(|variant| !variant.fields.is_empty());
                        let cases = match sealed {
                            true => &language.sealed_cases,
                            false => &language.cases,
                        };
                        out.push_str(language.enum_open);
                        for variant in variants {
                            let (from_case, to_case) = match index {
                                0 => ((cases[0])(&variant.name), (cases[1])(&variant.name)),
                                _ => ((cases[1])(&variant.name), (cases[0])(&variant.name)),
                            };
                            let arm = match (sealed, variant.fields.as_slice()) {
                                (false, _) => language.enum_arm.to_string(),
                                (true, []) => language.sealed_arm.to_string(),
                                (true, [field]) if field.rust.is_empty() => {
                                    let content = content.as_deref().unwrap_or_else(|| panic!("{name}::{} carries a payload but {name} has no serde content name", variant.name));
                                    let payload = language.payloads[index].replace("{content}", content);
                                    let value = language.convert(&self.config, &field.type_name, &payload, index);
                                    language.sealed_arm_data.replace("{payload}", &payload).replace("{value}", &value)
                                }
                                (true, _) => panic!("{name}::{} carries named or multiple fields; a TypeShare twin renders those as a type of their own", variant.name),
                            };
                            out.push_str(&arm.replace("{from_type}", from).replace("{from_case}", &from_case).replace("{to_type}", to).replace("{to_case}", &to_case));
                        }
                        out.push_str(language.enum_close);
                    }
                    RemoteType::Record { fields, .. } => {
                        out.push_str(&language.record_open.replace("{to}", to));
                        for field in fields {
                            let (label, accessor) = field_names(field, index);
                            let value = match (field.skipped, index) {
                                (true, 0) => continue,
                                (true, _) => language.default_value(&self.config, name, field),
                                (false, _) => language.convert(&self.config, &field.type_name, &accessor, index),
                            };
                            out.push_str(&language.field.replace("{label}", &label).replace("{value}", &value));
                        }
                        out.push_str(language.record_close);
                    }
                    RemoteType::Code { .. } => unreachable!(),
                }
                out.push_str(language.close);
            }
        }
        out
    }
}

pub(crate) fn source_files(directory: &Path) -> Vec<std::path::PathBuf> {
    let Ok(entries) = fs::read_dir(directory) else {
        return Vec::new();
    };
    let mut files = Vec::new();
    for entry in entries.flatten() {
        let path = entry.path();
        match path.is_dir() {
            true => files.extend(source_files(&path)),
            false if path.extension().is_some_and(|extension| extension == "rs") => files.push(path),
            false => {}
        }
    }
    files.sort();
    files
}

fn declaration(line: &str) -> Option<(&'static str, String)> {
    ["enum", "struct"].into_iter().find_map(|keyword| {
        let name = line.strip_prefix(&format!("pub {keyword} "))?.trim_end_matches(" {").trim();
        (!name.is_empty() && !name.contains('<')).then(|| (keyword, name.to_string()))
    })
}

fn member(line: &str) -> Option<(String, Option<String>)> {
    let line = line.trim().split("//").next()?.trim().trim_end_matches(',');
    if line.is_empty() || line.starts_with('#') {
        return None;
    }
    match line.strip_prefix("pub ") {
        Some(field) => {
            let (name, type_name) = field.split_once(": ")?;
            Some((name.trim().to_string(), Some(type_name.trim().to_string())))
        }
        None => line.chars().all(|c| c.is_alphanumeric() || c == '_').then(|| (line.to_string(), None)),
    }
}

fn body<'a>(lines: &mut impl Iterator<Item = &'a str>) -> Vec<&'a str> {
    let mut depth = 1usize;
    let mut body = Vec::new();
    for line in lines.by_ref() {
        depth += line.matches('{').count();
        depth = depth.saturating_sub(line.matches('}').count());
        if depth == 0 {
            break;
        }
        body.push(line);
    }
    body
}

fn variants(name: &str, body: &[&str]) -> Vec<Variant> {
    let mut variants = Vec::new();
    let mut lines = body.iter();
    while let Some(line) = lines.next() {
        let trimmed = line.trim().split("//").next().unwrap_or_default().trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        if let Some((variant, rest)) = trimmed.split_once('(') {
            assert!(!trimmed.contains('{'), "{name}::{trimmed} mixes tuple and named fields");
            let types = rest.rsplit_once(')').map(|(types, _)| types).unwrap_or_default();
            variants.push(Variant {
                name: variant.trim().to_string(),
                fields: tuple_types(types).into_iter().map(|type_name| tuple_field(&type_name)).collect(),
            });
            continue;
        }
        let Some((variant, rest)) = trimmed.split_once('{') else {
            variants.push(Variant {
                name: trimmed.trim_end_matches(',').to_string(),
                fields: Vec::new(),
            });
            continue;
        };
        let fields = match rest.split_once('}') {
            Some((inline, _)) => inline.split(',').filter_map(variant_field).collect(),
            None => lines.by_ref().take_while(|line| !line.trim().starts_with('}')).filter_map(|line| variant_field(line)).collect(),
        };
        variants.push(Variant { name: variant.trim().to_string(), fields });
    }
    variants
}

/// Splits a tuple variant's types on the commas between them, keeping the ones inside a field
/// attribute or a generic argument, then drops the attributes: `#[serde(a = "b", c = "d")] Option<BigInt>`.
fn tuple_types(types: &str) -> Vec<String> {
    let mut fields = Vec::new();
    let mut depth = 0usize;
    let mut current = String::new();
    for character in types.chars() {
        match character {
            '<' | '(' | '[' => depth += 1,
            '>' | ')' | ']' => depth = depth.saturating_sub(1),
            ',' if depth == 0 => {
                fields.push(std::mem::take(&mut current));
                continue;
            }
            _ => {}
        }
        current.push(character);
    }
    fields.push(current);
    fields.iter().filter_map(|field| strip_attributes(field)).collect()
}

fn strip_attributes(field: &str) -> Option<String> {
    let mut rest = field.trim();
    while let Some(attribute) = rest.strip_prefix("#[") {
        let mut depth = 1usize;
        let end = attribute.char_indices().find(|(_, character)| {
            match character {
                '[' => depth += 1,
                ']' => depth -= 1,
                _ => {}
            }
            depth == 0
        })?;
        rest = attribute[end.0 + 1..].trim();
    }
    (!rest.is_empty()).then(|| rest.to_string())
}

fn tuple_field(type_name: &str) -> Field {
    Field {
        rust: String::new(),
        serialized: String::new(),
        type_name: type_name.to_string(),
        skipped: false,
    }
}

fn variant_field(line: &str) -> Option<Field> {
    let line = line.trim().split("//").next()?.trim().trim_end_matches(',');
    if line.is_empty() || line.starts_with('#') {
        return None;
    }
    let (name, type_name) = line.split_once(": ")?;
    Some(Field {
        rust: name.trim().to_string(),
        serialized: name.trim().to_string(),
        type_name: type_name.trim().to_string(),
        skipped: false,
    })
}

fn fields(body: &[&str], camel_case_fields: bool) -> Vec<Field> {
    let mut fields = Vec::new();
    let mut rename = None;
    let mut serialized_as = None;
    let mut skipped = false;
    for line in body {
        if let Some(value) = serde_rename(line.trim()) {
            rename = Some(value);
        } else if let Some(value) = typeshare_serialized_as(line.trim()) {
            serialized_as = Some(value);
        } else if line.trim() == "#[typeshare(skip)]" {
            skipped = true;
        } else if let Some((rust, Some(type_name))) = member(line) {
            fields.push(Field {
                serialized: rename.take().unwrap_or_else(|| match camel_case_fields {
                    true => camel_case(&rust),
                    false => rust.clone(),
                }),
                rust,
                type_name: serialized_as.take().unwrap_or(type_name),
                skipped: std::mem::take(&mut skipped),
            });
        }
    }
    fields
}

fn typeshare_serialized_as(line: &str) -> Option<String> {
    Some(line.strip_prefix("#[typeshare(serialized_as = \"")?.split('"').next()?.to_string())
}

fn serde_content(line: &str) -> Option<String> {
    Some(line.split("content = \"").nth(1)?.split('"').next()?.to_string())
}

fn serde_rename(line: &str) -> Option<String> {
    Some(line.strip_prefix("#[serde(rename = \"")?.split('"').next()?.to_string())
}

impl Generator {
    /// How a field type reads inside a `#[uniffi::remote]` declaration in gemstone.
    fn declared_type(&self, type_name: &str) -> String {
        let (inner, wrapper) = unwrap(type_name);
        let declared = match wrapper {
            Wrapper::Option | Wrapper::Vec => self.declared_type(inner),
            Wrapper::None => match self.config.declared(inner) {
                Some(declared) => declared.to_string(),
                None if self.config.is_scalar(inner) || self.types.iter().any(|other| other.name() == inner) => inner.to_string(),
                None => format!("primitives::{inner}"),
            },
        };
        match wrapper {
            Wrapper::Option => format!("Option<{declared}>"),
            Wrapper::Vec => format!("Vec<{declared}>"),
            Wrapper::None => declared,
        }
    }
}

#[derive(Debug, PartialEq)]
enum Wrapper {
    None,
    Option,
    Vec,
}

fn unwrap(type_name: &str) -> (&str, Wrapper) {
    for (prefix, wrapper) in [("Option<", Wrapper::Option), ("Vec<", Wrapper::Vec)] {
        if let Some(inner) = type_name.strip_prefix(prefix).and_then(|inner| inner.strip_suffix('>')) {
            return (inner, wrapper);
        }
    }
    (type_name, Wrapper::None)
}

fn field_names(field: &Field, index: usize) -> (String, String) {
    match index {
        0 => (field.serialized.clone(), camel_case(&field.rust)),
        _ => (camel_case(&field.rust), field.serialized.clone()),
    }
}

