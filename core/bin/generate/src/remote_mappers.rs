use std::fs;
use std::path::Path;

const HEADER: &str = "// Generated by `just generate-models`. Do not edit.\n// Declared in core/bin/generate/src/remote_mappers.rs.\n";
pub const REMOTE_TYPES_PATH: &str = "gemstone/src/models/remote_types.rs";
const PRIMITIVES_SOURCE: &str = "crates/primitives/src";
const SCALARS: &[&str] = &["String", "i8", "i16", "i32", "i64", "u8", "u16", "u32", "u64", "bool", "f32", "f64"];

const EXPOSED_TYPES: &[&str] = &["AssetType", "Asset", "RecentActivityType"];

const IDENTIFIERS: &[Identifier] = &[Identifier {
    type_name: "AssetId",
    swift: ["Primitives.AssetId(core: {})", "{}.identifier"],
    kotlin: ["{}.toAssetId()!!", "{}.toIdentifier()"],
}];

struct Identifier {
    type_name: &'static str,
    swift: [&'static str; 2],
    kotlin: [&'static str; 2],
}

pub enum RemoteType {
    Enum { name: String, variants: Vec<String> },
    Record { name: String, fields: Vec<Field> },
}

pub struct Field {
    rust: String,
    serialized: String,
    type_name: String,
}

impl RemoteType {
    fn name(&self) -> &str {
        match self {
            Self::Enum { name, .. } | Self::Record { name, .. } => name,
        }
    }
}

pub fn parse(root: &Path) -> Vec<RemoteType> {
    let mut found = Vec::new();
    let Ok(entries) = fs::read_dir(root.join(PRIMITIVES_SOURCE)) else {
        return found;
    };
    for entry in entries.flatten() {
        let Ok(source) = fs::read_to_string(entry.path()) else { continue };
        let mut lines = source.lines();
        while let Some(line) = lines.next() {
            let Some((keyword, name)) = declaration(line.trim()) else { continue };
            if !EXPOSED_TYPES.contains(&name.as_str()) {
                continue;
            }
            let body: Vec<&str> = lines.by_ref().take_while(|line| line.trim() != "}").collect();
            found.push(match keyword {
                "enum" => RemoteType::Enum {
                    name,
                    variants: body.iter().filter_map(|line| member(line).map(|(name, _)| name)).collect(),
                },
                _ => RemoteType::Record { name, fields: fields(&body) },
            });
        }
    }
    // Enums first: a record's fields may reference one.
    found.sort_by_key(|remote| matches!(remote, RemoteType::Record { .. }));
    found
}

fn declaration(line: &str) -> Option<(&'static str, String)> {
    ["enum", "struct"].into_iter().find_map(|keyword| {
        let name = line.strip_prefix(&format!("pub {keyword} "))?.trim_end_matches(" {").trim();
        (!name.is_empty() && !name.contains('<')).then(|| (keyword, name.to_string()))
    })
}

fn member(line: &str) -> Option<(String, Option<String>)> {
    let line = line.trim().split("//").next()?.trim().trim_end_matches(',');
    if line.is_empty() || line.starts_with('#') {
        return None;
    }
    match line.strip_prefix("pub ") {
        Some(field) => {
            let (name, type_name) = field.split_once(": ")?;
            Some((name.trim().to_string(), Some(type_name.trim().to_string())))
        }
        None => line.chars().all(|c| c.is_alphanumeric() || c == '_').then(|| (line.to_string(), None)),
    }
}

fn fields(body: &[&str]) -> Vec<Field> {
    let mut fields = Vec::new();
    let mut rename = None;
    for line in body {
        if let Some(value) = serde_rename(line.trim()) {
            rename = Some(value);
        } else if let Some((rust, Some(type_name))) = member(line) {
            fields.push(Field {
                serialized: rename.take().unwrap_or_else(|| rust.clone()),
                rust,
                type_name,
            });
        }
    }
    fields
}

fn serde_rename(line: &str) -> Option<String> {
    Some(line.strip_prefix("#[serde(rename = \"")?.split('"').next()?.to_string())
}

pub fn remote_types(types: &[RemoteType]) -> String {
    let mut names = types.iter().map(RemoteType::name).collect::<Vec<_>>();
    names.sort_unstable();
    let names = names.join(", ");
    let mut out = format!("{HEADER}\nuse primitives::{{{names}}};\n");
    for remote in types {
        match remote {
            RemoteType::Enum { name, variants } => {
                out.push_str(&format!("\n#[uniffi::remote(Enum)]\npub enum {name} {{\n"));
                out.push_str(&variants.iter().map(|variant| format!("    {variant},\n")).collect::<String>());
            }
            RemoteType::Record { name, fields } => {
                out.push_str(&format!("\n#[uniffi::remote(Record)]\npub struct {name} {{\n"));
                for field in fields {
                    let known = types.iter().any(|other| other.name() == field.type_name) || SCALARS.contains(&field.type_name.as_str());
                    let declared = match known {
                        true => field.type_name.clone(),
                        false => format!("primitives::{}", field.type_name),
                    };
                    out.push_str(&format!("    pub {}: {declared},\n", field.rust));
                }
            }
        }
        out.push_str("}\n");
    }
    out
}

struct Language {
    sides: [(&'static str, &'static str); 2],
    core_module: &'static str,
    app_module: &'static str,
    identifier: fn(&Identifier) -> [&'static str; 2],
}

impl Language {
    fn convert(&self, type_name: &str, expression: &str, index: usize) -> String {
        if SCALARS.contains(&type_name) {
            return expression.to_string();
        }
        match IDENTIFIERS.iter().find(|identifier| identifier.type_name == type_name) {
            Some(identifier) => (self.identifier)(identifier)[index].replace("{}", expression),
            None => format!("{expression}.{}()", self.sides[index].1),
        }
    }

    fn direction(&self, index: usize) -> (&'static str, &'static str, &'static str) {
        let (_, function) = self.sides[index];
        match index {
            0 => (self.core_module, self.app_module, function),
            _ => (self.app_module, self.core_module, function),
        }
    }
}

fn camel_case(name: &str) -> String {
    name.split('_')
        .enumerate()
        .map(|(index, part)| match index {
            0 => part.to_string(),
            _ => part[..1].to_ascii_uppercase() + &part[1..],
        })
        .collect()
}

fn screaming_snake_case(name: &str) -> String {
    let characters: Vec<char> = name.chars().collect();
    characters
        .iter()
        .enumerate()
        .flat_map(|(index, character)| {
            let separator = (character.is_ascii_uppercase() && index > 0 && !characters[index - 1].is_ascii_uppercase()).then_some('_');
            separator.into_iter().chain(character.to_ascii_uppercase().to_string().chars().collect::<Vec<_>>())
        })
        .collect()
}

fn swift_case(variant: &str) -> String {
    let characters: Vec<char> = variant.chars().collect();
    let run = match characters.iter().position(|character| !character.is_ascii_uppercase()) {
        None => characters.len(),
        Some(first) if characters[first].is_ascii_lowercase() => first.max(2) - 1,
        Some(first) => first,
    };
    characters
        .iter()
        .enumerate()
        .map(|(index, character)| match index < run {
            true => character.to_ascii_lowercase(),
            false => *character,
        })
        .collect()
}

fn field_names(field: &Field, index: usize) -> (String, String) {
    match index {
        0 => (field.serialized.clone(), camel_case(&field.rust)),
        _ => (camel_case(&field.rust), field.serialized.clone()),
    }
}

pub fn swift(types: &[RemoteType]) -> String {
    let language = Language {
        sides: [("", "map"), ("", "map")],
        core_module: "Gemstone",
        app_module: "Primitives",
        identifier: |identifier| identifier.swift,
    };
    let mut out = format!("{HEADER}\nimport Gemstone\nimport Primitives\n");
    for remote in types {
        for index in 0..2 {
            let (from, to, function) = language.direction(index);
            let name = remote.name();
            out.push_str(&format!("\npublic extension {from}.{name} {{\n    func {function}() -> {to}.{name} {{\n"));
            match remote {
                RemoteType::Enum { variants, .. } => {
                    out.push_str("        switch self {\n");
                    for variant in variants {
                        out.push_str(&format!("        case .{case}: .{case}\n", case = swift_case(variant)));
                    }
                    out.push_str("        }\n");
                }
                RemoteType::Record { fields, .. } => {
                    out.push_str(&format!("        {to}.{name}(\n"));
                    for field in fields {
                        let (label, accessor) = field_names(field, index);
                        out.push_str(&format!("            {label}: {},\n", language.convert(&field.type_name, &accessor, index)));
                    }
                    out.push_str("        )\n");
                }
            }
            out.push_str("    }\n}\n");
        }
    }
    out
}

pub fn kotlin(types: &[RemoteType]) -> String {
    let language = Language {
        sides: [("", "toPrimitives"), ("", "toGem")],
        core_module: "uniffi.gemstone",
        app_module: "com.wallet.core.primitives",
        identifier: |identifier| identifier.kotlin,
    };
    let mut out = format!("{HEADER}\npackage com.gemwallet.android.ext\n");
    for remote in types {
        for index in 0..2 {
            let (from, to, function) = language.direction(index);
            let name = remote.name();
            out.push_str(&format!("\nfun {from}.{name}.{function}(): {to}.{name} = "));
            match remote {
                RemoteType::Enum { variants, .. } => {
                    out.push_str("when (this) {\n");
                    for variant in variants {
                        let (left, right) = match index {
                            0 => (screaming_snake_case(variant), variant.clone()),
                            _ => (variant.clone(), screaming_snake_case(variant)),
                        };
                        out.push_str(&format!("    {from}.{name}.{left} -> {to}.{name}.{right}\n"));
                    }
                }
                RemoteType::Record { fields, .. } => {
                    out.push_str(&format!("{to}.{name}(\n"));
                    for field in fields {
                        let (label, accessor) = field_names(field, index);
                        out.push_str(&format!("    {label} = {},\n", language.convert(&field.type_name, &accessor, index)));
                    }
                }
            }
            out.push_str(match remote {
                RemoteType::Enum { .. } => "}\n",
                RemoteType::Record { .. } => ")\n",
            });
        }
    }
    out
}
