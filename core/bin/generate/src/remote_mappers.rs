impl Language {
    fn convert(&self, config: &Config, type_name: &str, expression: &str, index: usize) -> String {
        let (inner, wrapper) = unwrap(type_name);
        let template = match wrapper {
            Wrapper::Option => Some(self.optional),
            Wrapper::Vec => Some(self.vec),
            Wrapper::None => None,
        };
        if let Some(template) = template {
            let converted = self.convert(config, inner, self.element, index);
            return match converted == self.element {
                true => expression.to_string(),
                false => template.replace("{}", expression).replace("{inner}", &converted),
            };
        }
        let template = match inner {
            name if config.conversion(name, self.name, index).is_some() => {
                return config.conversion(name, self.name, index).unwrap_or_default().replace("{}", expression);
            }
            name if config.is_scalar(name) || config.declared(name).is_some() => return expression.to_string(),
            name if config.codes.iter().any(|code| code == name) => self.codes[index],
            name if config.identifiers.iter().any(|identifier| identifier == name) => self.identifiers[index],
            _ => return format!("{expression}.{}()", self.functions[index]),
        };
        template.replace("{name}", inner).replace("{}", expression)
    }

    fn default_value(&self, config: &Config, record: &str, field: &Field) -> String {
        match unwrap(&field.type_name) {
            (_, Wrapper::Option) => self.none.to_string(),
            (_, Wrapper::Vec) => self.empty_vec.to_string(),
            ("String", _) => "\"\"".to_string(),
            ("bool", _) => "false".to_string(),
            ("f64", _) => "0.0".to_string(),
            (name, _) if config.is_scalar(name) => "0".to_string(),
            (name, _) if config.default_variant(name).is_some() => {
                let variant = config.default_variant(name).unwrap_or_default();
                format!("{}.{}.{}", self.core_module, name, (self.cases[0])(variant))
            }
            (name, _) => panic!("{record}.{} is skipped by TypeShare and {name} has no default the generator can emit", field.rust),
        }
    }
}

pub(crate) fn camel_case(name: &str) -> String {
    name.split('_')
        .enumerate()
        .map(|(index, part)| match index {
            0 => part.to_string(),
            _ => part[..1].to_ascii_uppercase() + &part[1..],
        })
        .collect()
}

pub(crate) fn screaming_snake_case(name: &str) -> String {
    let characters: Vec<char> = name.chars().collect();
    characters
        .iter()
        .enumerate()
        .flat_map(|(index, character)| {
            let separator = (character.is_ascii_uppercase() && index > 0 && !characters[index - 1].is_ascii_uppercase()).then_some('_');
            separator.into_iter().chain(character.to_ascii_uppercase().to_string().chars().collect::<Vec<_>>())
        })
        .collect()
}

pub(crate) fn swift_case(variant: &str) -> String {
    let characters: Vec<char> = variant.chars().collect();
    let run = match characters.iter().position(|character| !character.is_ascii_uppercase()) {
        None => characters.len(),
        Some(first) if characters[first].is_ascii_lowercase() => first.max(2) - 1,
        Some(first) => first,
    };
    characters
        .iter()
        .enumerate()
        .map(|(index, character)| match index < run {
            true => character.to_ascii_lowercase(),
            false => *character,
        })
        .collect()
}

pub(crate) fn uniffi_swift_case(variant: &str) -> String {
    let mut words: Vec<String> = Vec::new();
    let characters: Vec<char> = variant.chars().collect();
    let mut word = String::new();
    for (index, character) in characters.iter().enumerate() {
        let starts_word = character.is_ascii_uppercase() && !word.is_empty() && (characters[index - 1].is_ascii_lowercase() || characters.get(index + 1).is_some_and(char::is_ascii_lowercase));
        if starts_word {
            words.push(std::mem::take(&mut word));
        }
        word.push(*character);
    }
    if !word.is_empty() {
        words.push(word);
    }
    words
        .iter()
        .enumerate()
        .map(|(index, word)| match index {
            0 => word.to_ascii_lowercase(),
            _ => word[..1].to_ascii_uppercase() + &word[1..].to_ascii_lowercase(),
        })
        .collect()
}

/// UniFFI lowers a variant with `heck`, which treats a run of capitals as one word: `TransferNFT`
/// becomes `transferNft`, where TypeShare keeps `transferNFT`. The two sides of a mapper therefore
/// spell the same variant differently whenever it contains an acronym.
fn uniffi_type_name(name: &str) -> String {
    let camel = uniffi_swift_case(name);
    camel[..1].to_ascii_uppercase() + &camel[1..]
}

