use config::{File, FileFormat};
use serde::Deserialize;
use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

pub const HEADER: &str = "// Generated by `just generate-models`. Do not edit.\n// Declared in core/bin/generate/remote_types.yml.\n";
pub const REMOTE_TYPES_PATH: &str = "gemstone/src/models/remote_types.rs";
pub const PRIMITIVES_SOURCE: &str = "crates/primitives/src";
const CONFIG: &str = include_str!("../remote_types.yml");

/// `remote_types.yml`: the types that cross, and every type name the generator has to know.
#[derive(Deserialize)]
pub struct Config {
    remote: Vec<String>,
    codes: Vec<String>,
    identifiers: Vec<String>,
    scalars: Vec<String>,
    declared: BTreeMap<String, String>,
}

impl Config {
    pub fn from_yaml(yaml: &str) -> Self {
        config::Config::builder()
            .add_source(File::from_str(yaml, FileFormat::Yaml))
            .build()
            .and_then(|config| config.try_deserialize())
            .expect("remote_types.yml is malformed")
    }

    fn is_scalar(&self, name: &str) -> bool {
        self.scalars.iter().any(|scalar| scalar == name)
    }

    /// A type gemstone declares under another name, such as a big integer or a date.
    fn declared(&self, name: &str) -> Option<&str> {
        self.declared.get(name).map(String::as_str)
    }

    /// The declared names that are gemstone custom types, which the declarations import.
    fn custom_types<'a>(&'a self, types: &'a [RemoteType]) -> Vec<&'a str> {
        self.declared
            .iter()
            .filter(|(rust, declared)| !declared.contains("::") && types.iter().any(|remote| remote.field_types().iter().any(|type_name| unwrap(type_name).0 == rust.as_str())))
            .map(|(_, declared)| declared.as_str())
            .collect()
    }
}

pub enum RemoteType {
    Enum {
        name: String,
        module: String,
        variants: Vec<Variant>,
        typeshared: bool,
    },
    Record {
        name: String,
        module: String,
        fields: Vec<Field>,
        typeshared: bool,
    },
    Code {
        name: String,
    },
}

pub struct Variant {
    name: String,
    fields: Vec<Field>,
}

pub struct Field {
    rust: String,
    serialized: String,
    type_name: String,
    skipped: bool,
}

impl RemoteType {
    fn name(&self) -> &str {
        match self {
            Self::Enum { name, .. } | Self::Record { name, .. } | Self::Code { name } => name,
        }
    }

    fn module(&self) -> &str {
        match self {
            Self::Enum { module, .. } | Self::Record { module, .. } => module,
            Self::Code { .. } => "",
        }
    }

    fn typeshared(&self) -> bool {
        match self {
            Self::Enum { typeshared, .. } | Self::Record { typeshared, .. } => *typeshared,
            Self::Code { .. } => true,
        }
    }

    fn field_types(&self) -> Vec<&str> {
        match self {
            Self::Enum { variants, .. } => variants.iter().flat_map(|variant| variant.fields.iter().map(|field| field.type_name.as_str())).collect(),
            Self::Record { fields, .. } => fields.iter().map(|field| field.type_name.as_str()).collect(),
            Self::Code { .. } => Vec::new(),
        }
    }
}

/// The remote types declared in `remote_types.yml`, read once from the primitives sources.
pub struct Generator {
    config: Config,
    types: Vec<RemoteType>,
}

impl Generator {
    pub fn load(root: &Path) -> Self {
        Self::parse(Config::from_yaml(CONFIG), &root.join(PRIMITIVES_SOURCE))
    }

    pub fn parse(config: Config, primitives: &Path) -> Self {
        let mut found = Vec::new();
        for path in source_files(primitives) {
            let Ok(source) = fs::read_to_string(&path) else { continue };
            let module = path
                .strip_prefix(primitives)
                .ok()
                .and_then(Path::parent)
                .map(|parent| {
                    parent
                        .components()
                        .map(|component| component.as_os_str().to_string_lossy().into_owned())
                        .collect::<Vec<_>>()
                        .join(".")
                })
                .unwrap_or_default();
            let mut lines = source.lines();
            let mut typeshare = false;
            let mut camel_case_fields = false;
            while let Some(line) = lines.next() {
                let Some((keyword, name)) = declaration(line.trim()) else {
                    let attribute = line.trim().starts_with("#[");
                    typeshare = attribute && (typeshare || line.trim().starts_with("#[typeshare"));
                    camel_case_fields = attribute && (camel_case_fields || line.trim() == "#[serde(rename_all = \"camelCase\")]");
                    continue;
                };
                let declared = std::mem::take(&mut typeshare);
                let camel = std::mem::take(&mut camel_case_fields);
                if config.codes.contains(&name) {
                    if !declared {
                        continue;
                    }
                    assert_eq!(keyword, "enum", "{name} crosses as a code but is not an enum");
                    found.push(RemoteType::Code { name });
                    continue;
                }
                if !config.remote.contains(&name) {
                    continue;
                }
                let body = body(&mut lines);
                found.push(match keyword {
                    "enum" => RemoteType::Enum {
                        variants: variants(&name, &body),
                        name,
                        module: module.clone(),
                        typeshared: declared,
                    },
                    _ => RemoteType::Record {
                        name,
                        module: module.clone(),
                        fields: fields(&body, camel),
                        typeshared: declared,
                    },
                });
            }
        }
        for name in config.remote.iter().chain(&config.codes) {
            let typeshared = found.iter().filter(|remote| remote.name() == name && remote.typeshared()).count();
            if typeshared > 0 {
                found.retain(|remote| remote.name() != name || remote.typeshared());
            }
            let declarations = found.iter().filter(|remote| remote.name() == name).count();
            assert!(
                declarations == 1,
                "{name} has {declarations} declarations in {}, expected exactly one TypeShare declaration or one plain one",
                primitives.display()
            );
        }
        found.sort_by_key(|remote| (matches!(remote, RemoteType::Record { .. }), remote.name().to_string()));
        Self { config, types: found }
    }

    pub fn is_empty(&self) -> bool {
        self.types.is_empty()
    }

    /// The `#[uniffi::remote]` declarations gemstone compiles.
    pub fn remote_types(&self) -> String {
        let types = &self.types;
        let mut names = types.iter().map(RemoteType::name).collect::<Vec<_>>();
        names.sort_unstable();
        let mut out = format!("{HEADER}\nuse primitives::{{{}}};\n", names.join(", "));
        if types.iter().any(|remote| matches!(remote, RemoteType::Code { .. })) {
            out.push_str("use std::str::FromStr;\n");
        }
        match self.config.custom_types(types).as_slice() {
            [] => {}
            [single] => out.push_str(&format!("use crate::models::custom_types::{single};\n")),
            many => out.push_str(&format!("use crate::models::custom_types::{{{}}};\n", many.join(", "))),
        }
        for remote in types {
            match remote {
                RemoteType::Code { name } => out.push_str(&format!(
                    "\nuniffi::custom_type!({name}, String, {{\n    remote,\n    lower: |value| value.as_ref().to_string(),\n    try_lift: |value| {name}::from_str(&value).map_err(|_| uniffi::deps::anyhow::Error::msg(\"Invalid {name}\")),\n}});\n"
                )),
                RemoteType::Enum { name, variants, .. } => {
                    out.push_str(&format!("\n#[uniffi::remote(Enum)]\npub enum {name} {{\n"));
                    for variant in variants {
                        if variant.fields.is_empty() {
                            out.push_str(&format!("    {},\n", variant.name));
                            continue;
                        }
                        if variant.fields.iter().all(|field| field.rust.is_empty()) {
                            let types = variant.fields.iter().map(|field| self.declared_type(&field.type_name)).collect::<Vec<_>>();
                            out.push_str(&format!("    {}({}),\n", variant.name, types.join(", ")));
                            continue;
                        }
                        out.push_str(&format!("    {} {{\n", variant.name));
                        for field in &variant.fields {
                            out.push_str(&format!("        {}: {},\n", field.rust, self.declared_type(&field.type_name)));
                        }
                        out.push_str("    },\n");
                    }
                    out.push_str("}\n");
                }
                RemoteType::Record { name, fields, .. } => {
                    out.push_str(&format!("\n#[uniffi::remote(Record)]\npub struct {name} {{\n"));
                    for field in fields {
                        out.push_str(&format!("    pub {}: {},\n", field.rust, self.declared_type(&field.type_name)));
                    }
                    out.push_str("}\n");
                }
            }
        }
        out
    }

    pub fn swift(&self) -> String {
        self.mappers(&SWIFT)
    }

    pub fn kotlin(&self) -> String {
        self.mappers(&KOTLIN)
    }

    /// One `map()` / `toPrimitives()` / `toGem()` per direction for every remote type that has a
    /// TypeShare twin; a type without one is held by the apps as the uniffi type itself.
    fn mappers(&self, language: &Language) -> String {
        let mut out = format!("{HEADER}\n{}", language.header);
        for remote in self.types.iter().filter(|remote| remote.typeshared()) {
            let name = remote.name();
            if let RemoteType::Code { .. } = remote {
                out.push_str(&language.code_mapper.replace("{name}", name));
                continue;
            }
            let core_type = format!("{}.{}", language.core_module, uniffi_type_name(name));
            let app_type = match (language.app_modules, remote.module()) {
                (true, module) if !module.is_empty() => format!("{}.{module}.{name}", language.app_module),
                _ => format!("{}.{name}", language.app_module),
            };
            for index in 0..2 {
                let (from, to) = match index {
                    0 => (&core_type, &app_type),
                    _ => (&app_type, &core_type),
                };
                out.push_str(&language.open.replace("{from}", from).replace("{function}", language.functions[index]).replace("{to}", to));
                match remote {
                    RemoteType::Enum { variants, .. } => {
                        out.push_str(language.enum_open);
                        for variant in variants {
                            assert!(
                                variant.fields.is_empty(),
                                "{name}::{} carries fields; a data-carrying enum crosses without a TypeShare twin",
                                variant.name
                            );
                            let (from_case, to_case) = match index {
                                0 => ((language.cases[0])(&variant.name), (language.cases[1])(&variant.name)),
                                _ => ((language.cases[1])(&variant.name), (language.cases[0])(&variant.name)),
                            };
                            out.push_str(
                                &language
                                    .enum_arm
                                    .replace("{from_type}", from)
                                    .replace("{from_case}", &from_case)
                                    .replace("{to_type}", to)
                                    .replace("{to_case}", &to_case),
                            );
                        }
                        out.push_str(language.enum_close);
                    }
                    RemoteType::Record { fields, .. } => {
                        out.push_str(&language.record_open.replace("{to}", to));
                        for field in fields {
                            let (label, accessor) = field_names(field, index);
                            let value = match (field.skipped, index) {
                                (true, 0) => continue,
                                (true, _) => language.default_value(&self.config, name, field),
                                (false, _) => language.convert(&self.config, &field.type_name, &accessor, index),
                            };
                            out.push_str(&language.field.replace("{label}", &label).replace("{value}", &value));
                        }
                        out.push_str(language.record_close);
                    }
                    RemoteType::Code { .. } => unreachable!(),
                }
                out.push_str(language.close);
            }
        }
        out
    }
}

pub(crate) fn source_files(directory: &Path) -> Vec<std::path::PathBuf> {
    let Ok(entries) = fs::read_dir(directory) else {
        return Vec::new();
    };
    let mut files = Vec::new();
    for entry in entries.flatten() {
        let path = entry.path();
        match path.is_dir() {
            true => files.extend(source_files(&path)),
            false if path.extension().is_some_and(|extension| extension == "rs") => files.push(path),
            false => {}
        }
    }
    files.sort();
    files
}

fn declaration(line: &str) -> Option<(&'static str, String)> {
    ["enum", "struct"].into_iter().find_map(|keyword| {
        let name = line.strip_prefix(&format!("pub {keyword} "))?.trim_end_matches(" {").trim();
        (!name.is_empty() && !name.contains('<')).then(|| (keyword, name.to_string()))
    })
}

fn member(line: &str) -> Option<(String, Option<String>)> {
    let line = line.trim().split("//").next()?.trim().trim_end_matches(',');
    if line.is_empty() || line.starts_with('#') {
        return None;
    }
    match line.strip_prefix("pub ") {
        Some(field) => {
            let (name, type_name) = field.split_once(": ")?;
            Some((name.trim().to_string(), Some(type_name.trim().to_string())))
        }
        None => line.chars().all(|c| c.is_alphanumeric() || c == '_').then(|| (line.to_string(), None)),
    }
}

fn body<'a>(lines: &mut impl Iterator<Item = &'a str>) -> Vec<&'a str> {
    let mut depth = 1usize;
    let mut body = Vec::new();
    for line in lines.by_ref() {
        depth += line.matches('{').count();
        depth = depth.saturating_sub(line.matches('}').count());
        if depth == 0 {
            break;
        }
        body.push(line);
    }
    body
}

fn variants(name: &str, body: &[&str]) -> Vec<Variant> {
    let mut variants = Vec::new();
    let mut lines = body.iter();
    while let Some(line) = lines.next() {
        let trimmed = line.trim().split("//").next().unwrap_or_default().trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        if let Some((variant, rest)) = trimmed.split_once('(') {
            assert!(!trimmed.contains('{'), "{name}::{trimmed} mixes tuple and named fields");
            let types = rest.rsplit_once(')').map(|(types, _)| types).unwrap_or_default();
            variants.push(Variant {
                name: variant.trim().to_string(),
                fields: types.split(',').map(str::trim).filter(|type_name| !type_name.is_empty()).map(tuple_field).collect(),
            });
            continue;
        }
        let Some((variant, rest)) = trimmed.split_once('{') else {
            variants.push(Variant {
                name: trimmed.trim_end_matches(',').to_string(),
                fields: Vec::new(),
            });
            continue;
        };
        let fields = match rest.split_once('}') {
            Some((inline, _)) => inline.split(',').filter_map(variant_field).collect(),
            None => lines
                .by_ref()
                .take_while(|line| !line.trim().starts_with('}'))
                .filter_map(|line| variant_field(line))
                .collect(),
        };
        variants.push(Variant {
            name: variant.trim().to_string(),
            fields,
        });
    }
    variants
}

fn tuple_field(type_name: &str) -> Field {
    Field {
        rust: String::new(),
        serialized: String::new(),
        type_name: type_name.to_string(),
        skipped: false,
    }
}

fn variant_field(line: &str) -> Option<Field> {
    let line = line.trim().split("//").next()?.trim().trim_end_matches(',');
    if line.is_empty() || line.starts_with('#') {
        return None;
    }
    let (name, type_name) = line.split_once(": ")?;
    Some(Field {
        rust: name.trim().to_string(),
        serialized: name.trim().to_string(),
        type_name: type_name.trim().to_string(),
        skipped: false,
    })
}

fn fields(body: &[&str], camel_case_fields: bool) -> Vec<Field> {
    let mut fields = Vec::new();
    let mut rename = None;
    let mut skipped = false;
    for line in body {
        if let Some(value) = serde_rename(line.trim()) {
            rename = Some(value);
        } else if line.trim() == "#[typeshare(skip)]" {
            skipped = true;
        } else if let Some((rust, Some(type_name))) = member(line) {
            fields.push(Field {
                serialized: rename.take().unwrap_or_else(|| match camel_case_fields {
                    true => camel_case(&rust),
                    false => rust.clone(),
                }),
                rust,
                type_name,
                skipped: std::mem::take(&mut skipped),
            });
        }
    }
    fields
}

fn serde_rename(line: &str) -> Option<String> {
    Some(line.strip_prefix("#[serde(rename = \"")?.split('"').next()?.to_string())
}

impl Generator {
    /// How a field type reads inside a `#[uniffi::remote]` declaration in gemstone.
    fn declared_type(&self, type_name: &str) -> String {
        let (inner, wrapper) = unwrap(type_name);
        let declared = match wrapper {
            Wrapper::Option | Wrapper::Vec => self.declared_type(inner),
            Wrapper::None => match self.config.declared(inner) {
                Some(declared) => declared.to_string(),
                None if self.config.is_scalar(inner) || self.types.iter().any(|other| other.name() == inner) => inner.to_string(),
                None => format!("primitives::{inner}"),
            },
        };
        match wrapper {
            Wrapper::Option => format!("Option<{declared}>"),
            Wrapper::Vec => format!("Vec<{declared}>"),
            Wrapper::None => declared,
        }
    }
}

#[derive(Debug, PartialEq)]
enum Wrapper {
    None,
    Option,
    Vec,
}

fn unwrap(type_name: &str) -> (&str, Wrapper) {
    for (prefix, wrapper) in [("Option<", Wrapper::Option), ("Vec<", Wrapper::Vec)] {
        if let Some(inner) = type_name.strip_prefix(prefix).and_then(|inner| inner.strip_suffix('>')) {
            return (inner, wrapper);
        }
    }
    (type_name, Wrapper::None)
}

fn field_names(field: &Field, index: usize) -> (String, String) {
    match index {
        0 => (field.serialized.clone(), camel_case(&field.rust)),
        _ => (camel_case(&field.rust), field.serialized.clone()),
    }
}

/// The syntax of one app language. Index 0 in every pair is the direction out of Core, index 1
/// the direction into it.
struct Language {
    header: &'static str,
    core_module: &'static str,
    app_module: &'static str,
    app_modules: bool,
    functions: [&'static str; 2],
    cases: [fn(&str) -> String; 2],
    code_mapper: &'static str,
    open: &'static str,
    close: &'static str,
    enum_open: &'static str,
    enum_arm: &'static str,
    enum_close: &'static str,
    record_open: &'static str,
    field: &'static str,
    record_close: &'static str,
    codes: [&'static str; 2],
    identifiers: [&'static str; 2],
    optional: &'static str,
    vec: &'static str,
    none: &'static str,
    empty_vec: &'static str,
    element: &'static str,
}

const SWIFT: Language = Language {
    header: "import Gemstone\nimport Primitives\n",
    core_module: "Gemstone",
    app_module: "Primitives",
    app_modules: false,
    functions: ["map", "map"],
    cases: [uniffi_swift_case, swift_case],
    code_mapper: "\npublic extension Primitives.{name} {\n    init(core: Gemstone.{name}) {\n        guard let value = Primitives.{name}(rawValue: core) else {\n            fatalError(\"Core returned a {name} this build does not know: \\(core)\")\n        }\n        self = value\n    }\n\n    func map() -> Gemstone.{name} {\n        rawValue\n    }\n}\n",
    open: "\npublic extension {from} {\n    func {function}() -> {to} {\n",
    close: "    }\n}\n",
    enum_open: "        switch self {\n",
    enum_arm: "        case .{from_case}: .{to_case}\n",
    enum_close: "        }\n",
    record_open: "        {to}(\n",
    field: "            {label}: {value},\n",
    record_close: "        )\n",
    codes: ["Primitives.{name}(core: {})", "{}.rawValue"],
    identifiers: ["Primitives.{name}(core: {})", "{}.identifier"],
    optional: "{}.map { {inner} }",
    vec: "{}.map { {inner} }",
    none: "nil",
    empty_vec: "[]",
    element: "$0",
};

const KOTLIN: Language = Language {
    header: "package com.gemwallet.android.ext\n",
    core_module: "uniffi.gemstone",
    app_module: "com.wallet.core.primitives",
    app_modules: true,
    functions: ["toPrimitives", "toGem"],
    cases: [screaming_snake_case, str::to_string],
    code_mapper: "\nfun uniffi.gemstone.{name}.to{name}(): com.wallet.core.primitives.{name} = com.wallet.core.primitives.{name}.entries.firstOrNull { it.string == this }\n    ?: throw IllegalStateException(\"Core returned a {name} this build does not know: $this\")\n\nfun com.wallet.core.primitives.{name}.toGem(): uniffi.gemstone.{name} = string\n",
    open: "\nfun {from}.{function}(): {to} = ",
    close: "",
    enum_open: "when (this) {\n",
    enum_arm: "    {from_type}.{from_case} -> {to_type}.{to_case}\n",
    enum_close: "}\n",
    record_open: "{to}(\n",
    field: "    {label} = {value},\n",
    record_close: ")\n",
    codes: ["{}.to{name}()", "{}.toGem()"],
    identifiers: ["com.wallet.core.primitives.{name}({})", "{}.toIdentifier()"],
    optional: "{}?.let { {inner} }",
    vec: "{}.map { {inner} }",
    none: "null",
    empty_vec: "emptyList()",
    element: "it",
};

impl Language {
    fn convert(&self, config: &Config, type_name: &str, expression: &str, index: usize) -> String {
        let (inner, wrapper) = unwrap(type_name);
        let template = match wrapper {
            Wrapper::Option => Some(self.optional),
            Wrapper::Vec => Some(self.vec),
            Wrapper::None => None,
        };
        if let Some(template) = template {
            let converted = self.convert(config, inner, self.element, index);
            return match converted == self.element {
                true => expression.to_string(),
                false => template.replace("{}", expression).replace("{inner}", &converted),
            };
        }
        let template = match inner {
            name if config.is_scalar(name) || config.declared(name).is_some() => return expression.to_string(),
            name if config.codes.iter().any(|code| code == name) => self.codes[index],
            name if config.identifiers.iter().any(|identifier| identifier == name) => self.identifiers[index],
            _ => return format!("{expression}.{}()", self.functions[index]),
        };
        template.replace("{name}", inner).replace("{}", expression)
    }

    fn default_value(&self, config: &Config, record: &str, field: &Field) -> String {
        match unwrap(&field.type_name) {
            (_, Wrapper::Option) => self.none.to_string(),
            (_, Wrapper::Vec) => self.empty_vec.to_string(),
            ("String", _) => "\"\"".to_string(),
            ("bool", _) => "false".to_string(),
            ("f64", _) => "0.0".to_string(),
            (name, _) if config.is_scalar(name) => "0".to_string(),
            (name, _) => panic!("{record}.{} is skipped by TypeShare and {name} has no default the generator can emit", field.rust),
        }
    }
}

fn camel_case(name: &str) -> String {
    name.split('_')
        .enumerate()
        .map(|(index, part)| match index {
            0 => part.to_string(),
            _ => part[..1].to_ascii_uppercase() + &part[1..],
        })
        .collect()
}

fn screaming_snake_case(name: &str) -> String {
    let characters: Vec<char> = name.chars().collect();
    characters
        .iter()
        .enumerate()
        .flat_map(|(index, character)| {
            let separator = (character.is_ascii_uppercase() && index > 0 && !characters[index - 1].is_ascii_uppercase()).then_some('_');
            separator.into_iter().chain(character.to_ascii_uppercase().to_string().chars().collect::<Vec<_>>())
        })
        .collect()
}

fn swift_case(variant: &str) -> String {
    let characters: Vec<char> = variant.chars().collect();
    let run = match characters.iter().position(|character| !character.is_ascii_uppercase()) {
        None => characters.len(),
        Some(first) if characters[first].is_ascii_lowercase() => first.max(2) - 1,
        Some(first) => first,
    };
    characters
        .iter()
        .enumerate()
        .map(|(index, character)| match index < run {
            true => character.to_ascii_lowercase(),
            false => *character,
        })
        .collect()
}

fn uniffi_swift_case(variant: &str) -> String {
    let mut words: Vec<String> = Vec::new();
    let characters: Vec<char> = variant.chars().collect();
    let mut word = String::new();
    for (index, character) in characters.iter().enumerate() {
        let starts_word =
            character.is_ascii_uppercase() && !word.is_empty() && (characters[index - 1].is_ascii_lowercase() || characters.get(index + 1).is_some_and(char::is_ascii_lowercase));
        if starts_word {
            words.push(std::mem::take(&mut word));
        }
        word.push(*character);
    }
    if !word.is_empty() {
        words.push(word);
    }
    words
        .iter()
        .enumerate()
        .map(|(index, word)| match index {
            0 => word.to_ascii_lowercase(),
            _ => word[..1].to_ascii_uppercase() + &word[1..].to_ascii_lowercase(),
        })
        .collect()
}

/// UniFFI lowers a variant with `heck`, which treats a run of capitals as one word: `TransferNFT`
/// becomes `transferNft`, where TypeShare keeps `transferNFT`. The two sides of a mapper therefore
/// spell the same variant differently whenever it contains an acronym.
fn uniffi_type_name(name: &str) -> String {
    let camel = uniffi_swift_case(name);
    camel[..1].to_ascii_uppercase() + &camel[1..]
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::json_bridge;
    use std::path::PathBuf;

    /// `testdata/` holds a `remote_types.yml`, one primitives source per generator feature under
    /// `primitives/`, a `json_bridge.rs`, and under `expected/` the exact files the generator must
    /// write for them. Run with `UPDATE_GOLDEN=1` to rewrite the expected files after a deliberate
    /// change, and read the diff before committing it.
    fn testdata() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("testdata")
    }

    fn generator() -> Generator {
        let yaml = fs::read_to_string(testdata().join("remote_types.yml")).unwrap();
        Generator::parse(Config::from_yaml(&yaml), &testdata().join("primitives"))
    }

    fn expect_generated(name: &str, actual: String) {
        let path = testdata().join("expected").join(name);
        if std::env::var_os("UPDATE_GOLDEN").is_some() {
            fs::write(&path, &actual).unwrap();
            return;
        }
        let expected = fs::read_to_string(&path).unwrap_or_else(|_| panic!("{} is missing; run the tests once with UPDATE_GOLDEN=1", path.display()));
        assert_eq!(
            actual, expected,
            "{name} no longer matches testdata/expected/{name}; rerun with UPDATE_GOLDEN=1 once the diff is intended"
        );
    }

    #[test]
    fn test_remote_declarations_match_the_expected_file() {
        expect_generated("remote_types.rs", generator().remote_types());
    }

    #[test]
    fn test_swift_mappers_match_the_expected_file() {
        expect_generated("RemoteTypeMappers.swift", generator().swift());
    }

    #[test]
    fn test_kotlin_mappers_match_the_expected_file() {
        expect_generated("RemoteTypeMappers.kt", generator().kotlin());
    }

    #[test]
    fn test_json_bridge_files_match_the_expected_files() {
        let bridge = testdata().join("json_bridge.rs");
        expect_generated("JsonBridge.swift", json_bridge::swift_json_bridge(&json_bridge::bridge_types(&bridge)));
        expect_generated(
            "TaggedJsonBridge.kt",
            json_bridge::kotlin_tagged_bridge(&json_bridge::tagged_bridge_types(&bridge, &testdata().join("primitives"))),
        );
    }

    #[test]
    fn test_core_type_names_follow_uniffi_casing() {
        assert_eq!(uniffi_type_name("NFTAsset"), "NftAsset");
        assert_eq!(uniffi_type_name("TPSLOrderData"), "TpslOrderData");
        assert_eq!(uniffi_type_name("AssetId"), "AssetId");
        assert_eq!(uniffi_type_name("UTXO"), "Utxo");
        assert_eq!(swift_case("TransferNFT"), "transferNFT");
        assert_eq!(uniffi_swift_case("TransferNFT"), "transferNft");
    }

    #[test]
    fn test_a_typeshare_declaration_wins_over_a_plain_one_with_the_same_name() {
        let generator = generator();
        let stake = generator.types.iter().find(|remote| remote.name() == "GasPriceType").unwrap();
        assert!(!stake.typeshared());
        assert_eq!(generator.types.iter().filter(|remote| remote.typeshared()).count(), 7);
    }

    #[test]
    fn test_body_stops_at_the_closing_brace_of_the_declaration_not_of_a_variant() {
        let mut lines = [
            "    Regular { gas_price: BigInt },",
            "    Eip1559 {",
            "        gas_price: BigInt,",
            "    },",
            "}",
            "impl GasPriceType {",
        ]
        .into_iter();
        let body = body(&mut lines);
        assert_eq!(body.len(), 4);
        assert_eq!(lines.next(), Some("impl GasPriceType {"));
    }
}
